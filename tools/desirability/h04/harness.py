"""H04 answer checks compiled and run like I3 R2/R3, but as an external caller.

Every code answer (a construction, a call, an expression over a result or an error) and every
type answer is checked inside a generated **integration test** of the SDK package,
`examples/<sdk>-sdk/tests/__h04_probe.rs`, in a throwaway copy of the pinned commit (`git archive`
of the bank's commit into `<repo>/target/tmp/h04-score-copy`). An integration test is a separate
crate: it sees only the SDK's public API (plus the package's dependencies), so an answer that
reaches a private generated control (Xero's private `wire` client) does not compile, as for a
real caller. The I3 sandboxes are reused unchanged:

- compile: `probes/score.py` `CompileSandbox` (bubblewrap, read-only copy, no network, empty
  environment, `cargo --offline --frozen`), driven by `probes/truth.py` `compile_rounds` (errors
  mapped to the generated block by line, failing blocks dropped, rebuilt until clean), with
  `--lib` replaced by `--test __h04_probe`;
- run: `probes/score.py` `sandbox_run` (bubblewrap, scratch directory the only writable path,
  loopback-only network, nonce-tagged records), one test per process;
- answer form: `probes/score.py` `call_form` (the R3 single-expression contract, form `value`
  only: no `?` anywhere), `lexes`, `GUARD`; an expression answer is checked with the same parser
  by wrapping it as `(<expr>, __h04).1.send().await`, so the same refusals apply to it
  (statements outside closures, `?`, `.await`, `return`, loops, items, attributes, macros other
  than `vec!`/`format!`);
- types: `probes/score.py` `r2_gate` and `r2_check_fn` (rustc identity behind an invariant
  marker), compiled in the same integration test (paths resolve as for a caller who wrote
  `use <sdk crate>::*;`), with a positive control per truth type;
- requests: `probes/truth.py` `exchanges`/`req_record` and `probes/score.py` `compare_requests`
  (method, path and query pairs in order, header names, header values, body).

A scenario is trusted Rust (from the sealed bank) with `{SLOT}` placeholders; each answer is
pasted on lines of its own inside `{ .. }`. A reply script gives each request its reply in order
(status, headers, body, an optional delay before the head, or a closed connection); a run has a
wall-clock limit (`limit_s`, default 20 s, under the run sandbox's 60 s). A run may have a second
receiver for a second service origin (`oauth_replies`; the scenario gets `oauth_base`); each
receiver's requests are recorded apart (`__h04_record2`). A scenario evaluates to the run's outcome string:
`@@OK <Debug of the value>`, `@@ERR <Display of the error>` or `@@SETUP <why>`.
"""
