HEADER = r'''//! Generated by tools/desirability/h04/harness.py: @@WHAT@@. Do not edit; regenerate.
#![allow(warnings, unused, dead_code, missing_docs, unreachable_code, non_snake_case, clippy::all)]
extern crate alloc;
use ::@@CRATE@@::*;
// std collections an answer may name unqualified (`BTreeMap<String, Ticker>` for an SDK alias)
#[allow(unused_imports)]
use ::std::collections::{BTreeMap, HashMap};
use ::@@TESTSERVER@@ as __h04_ts;

fn __esc(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 2);
    o.push('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c if (c as u32) < 0x20 => o.push_str(&format!("\\u{:04x}", c as u32)),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// The nonce the scorer left for this run (read once, then removed).
fn __take_nonce() -> String {
    match ::std::env::var("CONCORD_PROBE_NONCE_FILE") {
        Ok(p) => {
            let n = ::std::fs::read_to_string(&p).unwrap_or_default();
            let _ = ::std::fs::remove_file(&p);
            n.trim().to_string()
        }
        Err(_) => String::new(),
    }
}

/// One scripted reply of the local receiver.
struct __R {
    status: u16,
    headers: &'static [(&'static str, &'static str)],
    body: &'static [u8],
    hang_up: bool,
    delay_ms: u64,
}

fn __reply(r: &__R) -> __h04_ts::Reply {
    if r.hang_up {
        return __h04_ts::Reply::hang_up();
    }
    let mut x = __h04_ts::Reply::new(r.status);
    for (k, v) in r.headers {
        x = x.header(k, *v);
    }
    if r.delay_ms > 0 {
        x = x.delay(::std::time::Duration::from_millis(r.delay_ms));
    }
    x.body(r.body)
}

fn __h04_ok<T: ::core::fmt::Debug>(v: &T) -> String {
    format!("@@OK {:?}", v)
}

fn __h04_err<E: ::core::fmt::Display>(e: &E) -> String {
    format!("@@ERR {}", e)
}

/// A fresh directory name under the run's scratch directory (the only writable path).
fn __h04_dir(tag: &str) -> ::std::path::PathBuf {
    ::std::env::current_dir().expect("cwd").join(tag)
}

fn __h04_now() -> u64 {
    ::std::time::SystemTime::now().duration_since(::std::time::UNIX_EPOCH).expect("clock").as_secs()
}

fn __h04_print(id: &str, nonce: &str, reqs: &[__h04_ts::Recorded], outcome: &Option<String>, done: bool) {
    let head = format!("\"id\":{},\"part\":\"h04\",\"cand\":\"\",\"nonce\":{},\"fixture\":\"\",\"pass\":0", __esc(id), __esc(nonce));
    for (n, r) in reqs.iter().enumerate() {
        let mut hs = String::new();
        for (k, v) in &r.headers {
            if !hs.is_empty() {
                hs.push(',');
            }
            hs.push_str(&format!("[{},{}]", __esc(k), __esc(v)));
        }
        println!(
            "@@PROBE {{{},\"n\":{},\"of\":{},\"done\":{},\"method\":{},\"target\":{},\"headers\":[{}],\"body\":{}}}",
            head, n, reqs.len(), done, __esc(&r.method), __esc(&r.target), hs, __esc(&String::from_utf8_lossy(&r.body))
        );
    }
    let outcome = match outcome {
        None => "null".to_string(),
        Some(e) => __esc(e),
    };
    println!("@@PROBE {{{},\"summary\":true,\"of\":{},\"done\":{},\"outcome\":{}}}", head, reqs.len(), done, outcome);
}

async fn __h04_server(replies: &'static [__R]) -> __h04_ts::TestServer {
    let count = ::std::sync::Arc::new(::std::sync::atomic::AtomicUsize::new(0));
    __h04_ts::TestServer::start(move |_r: &__h04_ts::Recorded| {
        let i = count.fetch_add(1, ::std::sync::atomic::Ordering::SeqCst);
        __reply(&replies[i.min(replies.len() - 1)])
    })
    .await
}

/// Runs `run(base)` once against a fresh local receiver (request `n` gets `replies[min(n, last)]`)
/// and prints what it recorded, in the I3 record format (`@@PROBE`, nonce-tagged).
fn __h04_record<F, Fut>(id: &str, replies: &'static [__R], limit_s: u64, run: F)
where
    F: FnOnce(String) -> Fut,
    Fut: ::core::future::Future<Output = Option<String>>,
{
    let nonce = __take_nonce();
    let rt = ::tokio::runtime::Builder::new_current_thread().enable_all().build().expect("runtime");
    rt.block_on(async move {
        let server = __h04_server(replies).await;
        let out = ::tokio::time::timeout(::std::time::Duration::from_secs(limit_s), run(server.url())).await;
        let (outcome, done) = match out {
            Ok(o) => (o, true),
            Err(_) => (Some(format!("timed out after {} s", limit_s)), false),
        };
        __h04_print(id, &nonce, &server.requests(), &outcome, done);
    });
}

/// The same with two receivers, one per service origin (`run(api_base, oauth_base)`); each
/// receiver's requests are printed under its own id (`<id>` and `<id>#oauth`).
fn __h04_record2<F, Fut>(id: &str, replies: &'static [__R], oauth_replies: &'static [__R], limit_s: u64, run: F)
where
    F: FnOnce(String, String) -> Fut,
    Fut: ::core::future::Future<Output = Option<String>>,
{
    let nonce = __take_nonce();
    let rt = ::tokio::runtime::Builder::new_current_thread().enable_all().build().expect("runtime");
    rt.block_on(async move {
        let api = __h04_server(replies).await;
        let oauth = __h04_server(oauth_replies).await;
        let out = ::tokio::time::timeout(::std::time::Duration::from_secs(limit_s), run(api.url(), oauth.url())).await;
        let (outcome, done) = match out {
            Ok(o) => (o, true),
            Err(_) => (Some(format!("timed out after {} s", limit_s)), false),
        };
        __h04_print(id, &nonce, &api.requests(), &outcome, done);
        __h04_print(&format!("{}#oauth", id), &nonce, &oauth.requests(), &outcome, done);
    });
}
'''


def header(crate, testserver, what):
    return HEADER.replace("@@CRATE@@", crate).replace("@@TESTSERVER@@", testserver).replace("@@WHAT@@", what)


def rust_bytes(body):
    return C.rust_str(body) + ".as_bytes()"


def replies_static(replies, fixture_root, name="__REPLIES"):
    """`static <name>: &[__R]` for a reply script; bodies are embedded literally."""
    items = []
    if not replies:  # a run that sends nothing still needs a reply script; never served
        replies = [{"status": 599, "headers": [], "body": "no request expected"}]
    for r in replies:
        if r.get("hang_up"):
            items.append("__R { status: 0, headers: &[], body: b\"\", hang_up: true, delay_ms: 0 }")
            continue
        body = r.get("body", "")
        if r.get("body_file"):
            body = open(os.path.join(fixture_root, r["body_file"]), encoding="utf-8").read()
        hs = ", ".join(f"({C.rust_str(k)}, {C.rust_str(v)})" for k, v in r.get("headers", []))
        items.append(f"__R {{ status: {int(r.get('status', 200))}, headers: &[{hs}], body: {rust_bytes(body)}, hang_up: false, "
                     f"delay_ms: {int(r.get('delay_ms', 0))} }}")
    return f"static {name}: &[__R] = &[\n        " + ",\n        ".join(items) + ",\n    ];"


def fill(scenario, slots):
    """The scenario with each `{SLOT}` replaced by its code on lines of its own."""
    names = set(re.findall(r"\{([A-Z][A-Z0-9_]*)\}", scenario))
    if names != set(slots):
        raise ValueError(f"scenario slots {sorted(names)} but answers for {sorted(slots)}")
    # one pass over the trusted template: answer text is never rescanned for placeholders
    return re.sub(r"\{([A-Z][A-Z0-9_]*)\}", lambda m: "\n" + slots[m.group(1)] + "\n", scenario)


RUN_LIMIT_S = 20  # default wall-clock limit of one scripted exchange (a run may set `limit_s`, < the sandbox's 60 s)


def test_fn(tag, rid, replies, body, fixture_root, limit_s=RUN_LIMIT_S, oauth_replies=None):
    if oauth_replies is not None:  # two receivers: `base` (the API origin) and `oauth_base`
        return (f"#[test]\nfn __h04_{tag}() {{\n    {replies_static(replies, fixture_root)}\n"
                f"    {replies_static(oauth_replies, fixture_root, '__REPLIES_OAUTH')}\n"
                f"    __h04_record2({C.rust_str(rid)}, __REPLIES, __REPLIES_OAUTH, {int(limit_s)}, "
                f"|base: String, oauth_base: String| async move {{\n{body}\n    }});\n}}")
    return (f"#[test]\nfn __h04_{tag}() {{\n    {replies_static(replies, fixture_root)}\n"
            f"    __h04_record({C.rust_str(rid)}, __REPLIES, {int(limit_s)}, |base: String| async move {{\n{body}\n    }});\n}}")


# ---------------------------------------------------------------- answer forms

EXPR_FORM_WRAP = "({}, __h04).1.send().await"


def check_form(code, form):
    """(code to paste, None) or (None, refusal) for one code answer. `call`: the R3 contract (one
    expression ending in `.send().await`, form `value` only). `expr`: one expression, the same
    refusals (checked through the wrapper `(<expr>, __h04).1.send().await`)."""
    if not isinstance(code, str) or not code.strip():
        return None, "no code"
    g = S.GUARD.search(code)
    if g:
        return None, f"refused before compiling (guard: `{g.group(0)}`)"
    if not S.lexes(code):
        return None, "not balanced Rust tokens (unbalanced delimiters, or an unterminated literal or comment)"
    if form == "call":
        body, f, why = S.call_form(code)
        if f is None:
            return None, f"refused before compiling (answer contract): {why}"
        if f != "value":
            return None, "refused before compiling (answer contract): a `?` after the final `.send().await` (no `?` anywhere)"
        return body, None
    c = code.strip()
    if c.endswith(";"):
        c = c[:-1].rstrip()
    wrapped = EXPR_FORM_WRAP.format(c)
    if not S.lexes(wrapped):
        return None, "not balanced Rust tokens"
    _, f, why = S.call_form(wrapped)
    if f != "value":
        return None, f"refused before compiling (expression contract): {why or 'not one expression'}"
    return c, None


# ---------------------------------------------------------------- copy, compile, run

def copy_commit(repo, commit):
    """`git archive <commit>` into `<repo>/target/tmp/h04-score-copy` (recreated)."""
    dest = os.path.join(repo, "target", "tmp", COPY_NAME)
    if os.path.isdir(dest):
        shutil.rmtree(dest)
    os.makedirs(dest)
    arch = subprocess.Popen(["git", "-C", repo, "archive", commit], stdout=subprocess.PIPE)
    subprocess.run(["tar", "-x", "-C", dest], stdin=arch.stdout, check=True)
    if arch.wait():
        raise SystemExit(f"git archive {commit} failed")
    return dest


class Batch:
    """Generated blocks for one compile: per SDK one integration-test module.

    `tree`, `target_dir`, `run_root` (all optional; used by `tools/desirability/pilot/`): an
    already materialised tree of `commit` whose provenance the caller checked (no `git archive`
    here), the cargo target directory to compile into (default `C.CARGO_TARGET_DIR`) and the
    directory of the run sandbox's scratch directories. Without them the behaviour is unchanged."""

    def __init__(self, repo, commit, sdks, fixture_roots, tree=None, target_dir=None, run_root=None):
        self.repo, self.commit, self.sdks, self.fixture_roots = repo, commit, sdks, fixture_roots
        self.tree, self.target_dir, self.run_root = tree, target_dir, run_root
        self.copy_root = tree or os.path.join(repo, "target", "tmp", COPY_NAME)
        self.modules = {}   # sdk short -> T.Module
        self.runs = {}      # key -> (sdk short, test fn name, rid)
        self.types = {}     # key -> block tag
        self.controls = {}  # truth text -> block tag (per sdk)
        self.two_receivers = set()  # run keys with a separate OAuth receiver

    def module(self, short):
        if short not in self.modules:
            info = self.sdks[short]
            sdk_dir = os.path.join(self.copy_root, "examples", info["dir"])
            path = os.path.join(sdk_dir, "tests", f"{TEST_NAME}.rs")
            ts = T.testserver_crate(os.path.join(self.tree or self.repo, "examples", info["dir"]))
            self.modules[short] = T.Module(info["pkg"], None, path, header(info["crate"], ts, f"H04 checks for `{short}`"))
        return self.modules[short]

    def add_run(self, key, short, tag, replies, body, limit_s=RUN_LIMIT_S, oauth_replies=None):
        tag = re.sub(r"\W", "_", tag)
        rid = "|".join(str(k) for k in key)
        m = self.module(short)
        m.add(f"run:{tag}", test_fn(tag, rid, replies, body, self.fixture_roots[short], limit_s, oauth_replies))
        self.runs[key] = (short, f"__h04_{tag}", rid, f"run:{tag}")
        if oauth_replies is not None:
            self.two_receivers.add(key)

    def add_type(self, key, short, tag, truth, answer):
        tag = re.sub(r"\W", "_", tag)
        m = self.module(short)
        ctl = self.controls.setdefault((short, truth), f"ctl:{short}:{len(self.controls)}")
        if not any(t == ctl for t, _ in m.blocks):
            m.add(ctl, S.r2_check_fn("__h04_ctl_" + re.sub(r"\W", "_", ctl), truth, truth))
        m.add(f"type:{tag}", S.r2_check_fn(f"__h04_type_{tag}", truth, answer))
        self.types[key] = (f"type:{tag}", ctl)

    def compile_and_run(self, log, sandbox=True):
        """Compile every module in the sandbox, run every runnable test. Returns
        ({key: result}, failed blocks)."""
        if not (os.access(S.BWRAP, os.X_OK) and shutil.which("timeout")):
            raise SystemExit(f"H04 checks need {S.BWRAP} and timeout(1): refusing to compile answers without a sandbox")
        if self.tree is None:
            copy_commit(self.repo, self.commit)
        mods = list(self.modules.values())
        if not mods:
            return {}, {}
        exes = {}
        box = S.CompileSandbox(self.copy_root, self.target_dir or C.CARGO_TARGET_DIR) if sandbox else None

        def runner(cwd, args):
            args = list(args)
            i = args.index("--lib")
            args[i:i + 1] = ["--test", TEST_NAME]
            r = box(cwd, args) if box else T.cargo(cwd, args)
            for line in r.stdout.splitlines():
                try:
                    ev = json.loads(line)
                except ValueError:
                    continue
                tgt = ev.get("target") or {}
                if ev.get("reason") == "compiler-artifact" and ev.get("executable") and tgt.get("name") == TEST_NAME:
                    pid = ev.get("package_id", "")
                    for m in mods:
                        if f"#{m.pkg}@" in pid or pid.startswith(m.pkg + " ") or f"/{m.pkg}#" in pid:
                            exes[m.pkg] = ev["executable"]
            return r

        log.append({"compile": box.describe() if box else "host cargo (trusted code only)",
                    "blocks": sum(len(m.blocks) for m in mods)})
        t0 = time.monotonic()
        # rustc names an integration test's file relative to the workspace root, and
        # `truth.map_error` resolves names against the current directory: compile from the copy
        cwd = os.getcwd()
        os.chdir(self.copy_root)
        try:
            failed = T.compile_rounds(self.copy_root, mods, log, artifacts=None, runner=runner)
        finally:
            os.chdir(cwd)
        log.append({"compile_seconds": round(time.monotonic() - t0, 1), "failed_blocks": len(failed)})
        T.write_modules(mods)
        results = {}
        run_root = self.run_root or os.path.join(self.repo, "target", "tmp", RUN_NAME)
        names = {}
        for short, m in self.modules.items():
            exe = exes.get(m.pkg)
            if exe:
                for n in S.list_tests(exe, os.path.join(run_root, "list")):
                    names[(short, n.rsplit("::", 1)[-1])] = (exe, n)
        jobs = []
        for key, (short, fname, rid, tag) in self.runs.items():
            if tag in failed:
                results[key] = {"compiles": False, "reason": "does not compile: " + failed[tag]}
                continue
            if (short, fname) not in names:
                results[key] = {"compiles": True, "reason": "test executable or test not found", "requests": [], "outcome": None}
                continue
            jobs.append((key, rid) + names[(short, fname)])
        from concurrent.futures import ThreadPoolExecutor
        t0 = time.monotonic()
        with ThreadPoolExecutor(max_workers=S.RUN_PARALLEL) as pool:
            futs = {pool.submit(S.sandbox_run, exe, [name, "--exact", "--nocapture", "--test-threads=1"],
                                os.path.join(run_root, str(i))): (key, rid) for i, (key, rid, exe, name) in enumerate(jobs)}
            for fut, (key, rid) in futs.items():
                recs, code, err, _, _ = fut.result()
                nonce = recs[0]["nonce"] if recs else ""
                passes, _ = T.exchanges({rid: [r for r in recs if r.get("id") == rid]}, rid, "h04", nonce=nonce)
                p0 = passes.get(0)
                if p0 is None or not p0["summary"]:
                    results[key] = {"compiles": True, "complete": False, "requests": [], "outcome": None,
                                    "reason": f"no complete record from the sandboxed run (exit {code}): {err[-300:]}"}
                    continue
                results[key] = {"compiles": True, "complete": True, "outcome": p0["outcome"],
                                "requests": [T.req_record(r, []) for r in p0["requests"]], "exit": code}
                if key in self.two_receivers:
                    po, _ = T.exchanges({rid + "#oauth": [r for r in recs if r.get("id") == rid + "#oauth"]}, rid + "#oauth", "h04",
                                        nonce=nonce)
                    po0 = po.get(0)
                    if po0 is None or not po0["summary"]:
                        results[key] = {"compiles": True, "complete": False, "requests": [], "outcome": None,
                                        "reason": "no complete record from the OAuth receiver"}
                    else:
                        results[key]["oauth_requests"] = [T.req_record(r, []) for r in po0["requests"]]
        log.append({"run_seconds": round(time.monotonic() - t0, 1), "runs": len(jobs)})
        for key, (tag, ctl) in self.types.items():
            if ctl in failed:
                results[key] = {"compiles": None, "reason": "positive control failed: " + failed[ctl]}
            elif tag in failed:
                results[key] = {"compiles": False, "reason": failed[tag]}
            else:
                results[key] = {"compiles": True}
        return results, failed
