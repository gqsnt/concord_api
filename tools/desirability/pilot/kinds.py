SOURCE_LINE = re.compile(r"^\s*\d+\s*[|:]")
FILE_LINE = re.compile(r"^\s*(?:-->|:::)\s+(.+?):\d+:\d+\s*$")
PANIC_PREFIX = re.compile(r"^thread '[^']*'(?: \(\d+\))? panicked at [^:]+:\d+:\d+:\s*")


def sdk_info(tree, sdk):
    d = os.path.join(tree, "examples", f"{sdk}-sdk")
    if not os.path.isfile(os.path.join(d, "Cargo.toml")):
        return None
    pkg = C.pkg_name(d)
    return {"dir": f"{sdk}-sdk", "pkg": pkg, "crate": pkg.replace("-", "_")}


def normalise(text, tree):
    """A diagnostic without the tree path, line/column numbers, ports, thread ids, durations or
    addresses (H08 `normalise` plus line/column numbers, as H03 `norm_diag`)."""
    t = re.sub(r"\x1b\[[0-9;]*m", "", text or "")
    t = t.replace(os.path.realpath(tree), "<tree>").replace(tree, "<tree>")
    t = re.sub(r"(\.rs):\d+:\d+", r"\1:L:C", t)
    t = re.sub(r"(?m)^(\s*)\d+(\s*\|)", r"\1N\2", t)
    t = re.sub(r"(127\.0\.0\.1|localhost|\[::1\]):\d+", r"\1:PORT", t)
    t = re.sub(r"(thread '[^']*') \(\d+\)", r"\1 (TID)", t)
    t = re.sub(r"\b\d+(\.\d+)?(ns|µs|us|ms|s)\b", "DUR", t)
    t = re.sub(r"0x[0-9a-f]{6,}", "0xADDR", t)
    t = re.sub(r"(?m)^note: run with `RUST_BACKTRACE=1` environment variable to display a backtrace\n?", "", t)
    return t.strip()


def diag_lines(rendered):
    """[(line, is a quoted source line, file it quotes)] of a rendered rustc diagnostic."""
    out, cur = [], None
    for ln in (rendered or "").splitlines():
        m = FILE_LINE.match(ln)
        if m:
            cur = m.group(1)
            out.append((ln, False, cur))
        else:
            out.append((ln, bool(SOURCE_LINE.match(ln)), cur))
    return out


# ---------------------------------------------------------------- compile

COMPILE_HEADER = ("//! Generated by tools/desirability/pilot (compile task). Do not edit.\n"
                  "#![allow(warnings, unused, dead_code, missing_docs, unreachable_code, non_snake_case, clippy::all)]\n")


def compile_source(t, crate):
    imports = t.get("imports", [f"use ::{crate}::*;"])
    code = t["code"].rstrip("\n")
    body = (f"#[allow(unused)]\nasync fn __pilot_snippet() {{\n{code}\n}}\n" if t.get("form", "body") == "body"
            else code + "\n")
    return COMPILE_HEADER + "\n".join(imports) + "\n\n" + body


def first_error(msgs, target_name):
    for ev in msgs:
        if ev.get("reason") != "compiler-message" or (ev.get("target") or {}).get("name") != target_name:
            continue
        m = ev.get("message") or {}
        if not str(m.get("level", "")).startswith("error"):
            continue
        if m.get("message", "").startswith("aborting due to") or m.get("message", "").startswith("could not compile"):
            continue
        return m
    return None


def primary_block(rendered):
    """I5 `diagnostics/score.py` `first_error` block: the headline and the following lines up to
    the first `= note`, `= help`, `note:` or `help:` line (quoted source lines included)."""
    out = []
    for i, ln in enumerate((rendered or "").splitlines()):
        if i and ln.strip().startswith(("= note", "= help", "note:", "help:")):
            break
        out.append(ln)
    return out


def word_in(s, text):
    """`s` occurs in `text`; as a whole word when it starts and ends with a word character (so a
    generated name does not match a longer one), else as a substring (`concord_core::`)."""
    if re.match(r"\w", s) and re.search(r"\w$", s):
        return re.search(r"(?<!\w)" + re.escape(s) + r"(?!\w)", text) is not None
    return s in text


def compile_verdict(t, res, snippet_rel):
    """(verdict, reason) of a compile task from {compiles, error message}."""
    exp = t["expect"]
    if res["compiles"] is None:
        return "invalid", res.get("reason", "not built")
    if exp["compiles"]:
        return ("pass", None) if res["compiles"] else ("fail", "does not compile: " + res["headline"])
    if res["compiles"]:
        return "fail", "compiles, expected a compile error"
    first = exp.get("first") or {}
    msg = res["message"]
    rendered = msg.get("rendered") or msg.get("message", "")
    lines = diag_lines(rendered)
    if first.get("scope") == "primary":  # I5 R5: the headline and the label lines under the primary span
        text = shown = "\n".join(primary_block(rendered))
    else:  # the whole diagnostic: quoted source lines excluded (mentions), the snippet's own quoted lines excluded (absent)
        text = "\n".join(ln for ln, src, _ in lines if not src)
        shown = "\n".join(ln for ln, src, f in lines if not (src and f and f.endswith(snippet_rel)))
    code = (msg.get("code") or {}).get("code")
    want = first.get("code")
    if want is not None and code not in ([want] if isinstance(want, str) else want):
        return "fail", f"first error {code} instead of {want}"
    for s in first.get("mentions", []):
        if not word_in(s, text):
            return "fail", f"first error does not name `{s}`"
    for s in first.get("absent", []):
        if word_in(s, shown):
            return "fail", f"first error names `{s}`"
    if "matches" in first and not re.search(first["matches"], text):
        return "fail", "first error does not match the expected pattern"
    if first.get("in_snippet"):
        prim = [sp for sp in msg.get("spans", []) if sp.get("is_primary")]
        if not prim or not all(sp.get("file_name", "").endswith(snippet_rel) for sp in prim):
            return "fail", "first error's primary span is not in the snippet"
    return "pass", None


def run_compile(tasks, ctx):
    """Every compile task on the arm's clean tree: one integration-test target per task (each
    snippet is its own crate, so its first diagnostic is the one a caller compiling it alone
    gets), built with `cargo build --keep-going` in the compile sandbox, one package per command."""
    out, by_pkg = {}, {}
    for i, t in enumerate(sorted(tasks, key=lambda x: x["id"])):
        info = sdk_info(ctx.tree, t["sdk"])
        if info is None:
            out[t["id"]] = {"verdict": "invalid", "reason": f"no SDK examples/{t['sdk']}-sdk on this arm"}
            continue
        name = f"__pilot_c{i:04d}"
        rel = os.path.join("examples", info["dir"], "tests", name + ".rs")
        with open(os.path.join(ctx.tree, rel), "w", encoding="utf-8") as f:
            f.write(compile_source(t, info["crate"]))
        by_pkg.setdefault(info["pkg"], []).append((t, name, rel))
    if not by_pkg:
        return out
    msgs, lib_errors = [], {}
    for pkg, items in sorted(by_pkg.items()):  # one package per cargo command (the `--test` selectors are per command)
        t0 = time.monotonic()
        r = ctx.cargo(["build", "--keep-going", "--message-format=json", "-p", pkg] + [x for _, name, _ in items for x in ("--test", name)])
        pm = [json.loads(ln) for ln in r.stdout.splitlines() if ln.startswith("{")]
        msgs += pm
        for ev in pm:
            tgt = ev.get("target") or {}
            if ev.get("reason") == "compiler-message" and not str(tgt.get("name", "")).startswith("__pilot_c") and \
                    str((ev.get("message") or {}).get("level", "")).startswith("error"):
                lib_errors.setdefault(pkg, (ev["message"].get("rendered") or "")[:400])
        if r.returncode and not any(ev.get("reason") == "compiler-message" for ev in pm):
            lib_errors.setdefault(pkg, (r.stderr or "")[-400:])  # cargo itself failed (no compiler message)
        ctx.log.append({"compile_package": pkg, "targets": len(items), "exit": r.returncode, "seconds": round(time.monotonic() - t0, 1)})
    built = {(ev.get("target") or {}).get("name") for ev in msgs if ev.get("reason") == "compiler-artifact"}
    for pkg, items in by_pkg.items():
        for t, name, rel in items:
            m = first_error(msgs, name)
            if m is not None:
                res = {"compiles": False, "message": m, "headline": f"{(m.get('code') or {}).get('code') or ''} {m.get('message', '')}".strip()}
            elif name in built:
                res = {"compiles": True}
            else:
                res = {"compiles": None, "reason": "not built (a dependency of the snippet failed to build on this arm)"
                       + (f": {lib_errors[pkg]}" if pkg in lib_errors else "")}
            verdict, why = compile_verdict(t, res, rel)
            rendered = normalise((res.get("message") or {}).get("rendered", ""), ctx.tree)
            out[t["id"]] = {"verdict": verdict, "reason": why, "compiles": res["compiles"],
                            "first_code": ((res.get("message") or {}).get("code") or {}).get("code"),
                            "first_rendered": rendered[:4000],
                            "fingerprint": [res["compiles"], ((res.get("message") or {}).get("code") or {}).get("code"), rendered]}
    return out


# ---------------------------------------------------------------- request

def request_body(t, debug_ok):
    imports = "\n".join("        " + x for x in t.get("imports", []))
    setup = t.get("setup", "")
    setup = "\n".join(setup) if isinstance(setup, list) else setup
    ok = "__h04_ok(__v)" if debug_ok else '"@@OK".to_string()'
    return (f"        async fn __pilot_s(base: String) -> ::core::result::Result<String, ::std::boxed::Box<dyn ::std::error::Error>> {{\n"
            f"{imports}\n{setup}\n"
            f"        let __r = {{\n{t['call']}\n        }};\n"
            f"        Ok(match &__r {{ ::core::result::Result::Ok(__v) => {ok}, ::core::result::Result::Err(__e) => __h04_err(__e) }})\n"
            f"        }}\n"
            f"        Some(match __pilot_s(base).await {{ Ok(s) => s, Err(e) => format!(\"@@SETUP {{}}\", e) }})")


def inline_replies(t):
    out = []
    for r in t["replies"]:
        r = dict(r)
        if "body_file" in r:
            with open(os.path.join(t["_dir"], r.pop("body_file")), encoding="utf-8") as f:
                r["body"] = f.read()
        out.append(r)
    return out


def request_verdict(t, res):
    exp = t["expect"]
    if res is None:
        return "invalid", "no result"
    if not res.get("compiles"):
        return "fail", "does not compile: " + str(res.get("reason") or "")[:300]
    if not res.get("complete"):
        return "fail", "incomplete run: " + str(res.get("reason") or "")[:300]
    outcome = res.get("outcome") or ""
    want = exp["requests"]
    ok_req, why, _ = S.compare_requests(res.get("requests") or [], {"recorded": want, "recorded_again": want,
                                                                    "volatile": {"headers": exp.get("volatile", {}).get("headers", [])}})
    if "outcome" in exp and outcome != exp["outcome"]:
        return "fail", f"outcome {outcome[:200]!r} instead of {exp['outcome'][:200]!r}" + ("" if ok_req else f"; different request: {why}")
    if exp.get("ok", True) and not outcome.startswith("@@OK"):
        return "fail", f"result not Ok: {outcome[:200]}" + ("" if ok_req else f"; different request: {why}")
    if not exp.get("ok", True) and not outcome.startswith("@@ERR"):
        return "fail", f"result not Err: {outcome[:200]}"
    if not ok_req:
        return "fail", f"compiles, completes, but sends a different request: {why}"
    return "pass", None


def run_requests(tasks, ctx):
    """Every request task on the arm's clean tree: compiled in the compile sandbox (H04 `Batch`,
    one integration-test module per SDK, failing blocks dropped and rebuilt) and run one test per
    process in the run sandbox against the scripted local receiver."""
    out, infos = {}, {}
    for t in tasks:
        infos.setdefault(t["sdk"], sdk_info(ctx.tree, t["sdk"]))
    sdks = {k: {**v, "short": k} for k, v in infos.items() if v}
    batch = H.Batch(A.REPO, ctx.sha, sdks, {k: ctx.tree for k in sdks}, tree=ctx.tree, target_dir=ctx.target,
                    run_root=os.path.join(ctx.scratch, "run"))
    tags = {}
    for i, t in enumerate(sorted(tasks, key=lambda x: x["id"])):
        if not infos.get(t["sdk"]):
            out[t["id"]] = {"verdict": "invalid", "reason": f"no SDK examples/{t['sdk']}-sdk on this arm"}
            continue
        tag = f"pilot_r{i:04d}"
        tags[t["id"]] = tag
        batch.add_run(t["id"], t["sdk"], tag, inline_replies(t), request_body(t, "outcome" in t["expect"]),
                      t.get("limit_s", H.RUN_LIMIT_S))
    if not tags:
        return out
    rendered, orig = {}, T.map_error

    def mapping(msg, spans):  # keep the first rendered error of each failing block (as H03's harness)
        tag = orig(msg, spans)
        if tag and tag not in rendered and str(msg.get("level", "")).startswith("error"):
            rendered[tag] = msg.get("rendered") or msg.get("message", "")
        return tag

    ctx.check()
    T.map_error = mapping
    try:
        results, _failed = batch.compile_and_run(ctx.log)
    finally:
        T.map_error = orig
    for t in tasks:
        if t["id"] not in tags:
            continue
        res = results.get(t["id"])
        verdict, why = request_verdict(t, res)
        diag = normalise(rendered.get(f"run:{tags[t['id']]}", ""), ctx.tree)
        reqs = (res or {}).get("requests") or []
        out[t["id"]] = {"verdict": verdict, "reason": why, "compiles": (res or {}).get("compiles"),
                        "outcome": (res or {}).get("outcome"), "requests": reqs, "first_rendered": diag[:4000],
                        "fingerprint": [verdict, (res or {}).get("compiles"), (res or {}).get("outcome"), reqs, diag]}
    return out


# ---------------------------------------------------------------- stage (H08)

def json_messages(text):
    out = []
    for ln in text.splitlines():
        if ln.startswith("{"):
            try:
                out.append(json.loads(ln))
            except ValueError:
                pass
    return out


def first_compiler_error(msgs, tree):
    for m in msgs:
        if m.get("reason") != "compiler-message":
            continue
        msg = m.get("message") or {}
        if msg.get("level") != "error" or (msg.get("message") or "").startswith("aborting due to"):
            continue
        return {"package_id": m.get("package_id"), "target": (m.get("target") or {}).get("name"),
                "code": (msg.get("code") or {}).get("code"), "message": msg.get("message"),
                "rendered": (msg.get("rendered") or "").replace(tree, "<tree>").rstrip()}
    return None


def freshness(msgs, tree):
    compiled, reused = set(), set()
    for m in msgs:
        if m.get("reason") == "compiler-artifact" and ("path+file://" + tree) in (m.get("package_id") or ""):
            (reused if m.get("fresh") else compiled).add((m.get("target") or {}).get("name"))
    return {"compiled": sorted(compiled), "reused": sorted(reused - compiled)}


def names_endpoint(text, pattern):
    if not pattern:
        return False, None
    for ln in (text or "").splitlines():
        if SOURCE_LINE.match(ln) or I4.TEST_BLOCK.match(ln):
            continue
        m = re.search(pattern, PANIC_PREFIX.sub("", ln))
        if m:
            return True, m.group(0)
    return False, None


def patches_for(t, arm):
    return t["patches"].get(arm) or t["patches"].get("*")


def stage_variant(t, variant, patch, ctx):
    """One variant (reference, omission or a control) of a stage task in a fresh tree: patch,
    SDK build, existing tests, oracle compile, oracle run. Returns the run record with `stage`."""
    tree, sha = ctx.stage_tree, ctx.sha
    A.materialise(sha, tree)
    info = sdk_info(tree, t["sdk"])
    rec = {"variant": variant, "patch": os.path.relpath(patch, ctx.tasks_dir), "patch_sha256": C.sha256_file(patch)}
    if info is None:
        return {**rec, "stage": "invalid: no such SDK on this arm"}
    pkg = t.get("package", info["pkg"])
    sdk_url = "path+file://" + os.path.join(tree, "examples", info["dir"])
    genv = {"PATH": "/usr/bin:/bin", "HOME": ctx.scratch, "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": "/dev/null"}
    for cmd in (["git", "apply", "--check", patch], ["git", "apply", patch]):
        r = subprocess.run(cmd, cwd=tree, env=genv, capture_output=True, text=True)
        if r.returncode:
            return {**rec, "stage": "invalid: patch does not apply", "error": (r.stdout + r.stderr)[-1000:]}
    # 1. SDK build
    r = ctx.cargo(["build", "-p", pkg, "--lib", "--message-format=json"], stage=True)
    msgs = json_messages(r.stdout)
    rec["freshness"] = freshness(msgs, tree)
    err = first_compiler_error(msgs, tree)
    if r.returncode:
        if err and (err["package_id"] or "").startswith(sdk_url):
            return conclude(rec, "SDK build", err["rendered"], err, t, tree)
        return {**rec, "stage": "invalid: the build failed outside the SDK package", "stderr": r.stderr[-1500:]}
    rec["freshness"]["sdk_compiled_now"] = info["crate"] in rec["freshness"]["compiled"]
    if not rec["freshness"]["sdk_compiled_now"]:
        return {**rec, "stage": "invalid: the SDK was not recompiled in this run (stale target)"}
    # 2. existing tests (no oracle yet)
    r = ctx.cargo(["test", "-p", pkg, "--no-fail-fast"], stage=True, merge=True)
    text = r.stdout
    rows = I4.targets(text)
    built = "could not compile" not in text
    rec["existing_tests"] = {"exit": r.returncode, "built": built,
                             "passed": r.returncode == 0 and bool(rows) and all(x["ok"] for x in rows),
                             "failed": sorted(n for x in rows for n, v in x["tests"].items() if v == "FAILED")}
    if not built:
        r2 = ctx.cargo(["test", "-p", pkg, "--no-run", "--message-format=json"], stage=True)
        e = first_compiler_error(json_messages(r2.stdout), tree)
        return conclude(rec, "caller compile (existing tests)", e and e["rendered"], e, t, tree)
    # 3. oracle compile
    oname = t.get("oracle_name", "pilot_oracle")
    dest = os.path.join(tree, "examples", info["dir"], "tests", oname + ".rs")
    if os.path.exists(dest):
        return {**rec, "stage": f"invalid: the tree already has tests/{oname}.rs"}
    with open(os.path.join(t["_dir"], t["oracle"]), encoding="utf-8") as f:
        oracle = f.read()
    with open(dest, "w", encoding="utf-8") as f:
        f.write(oracle)
    r = ctx.cargo(["test", "-p", pkg, "--test", oname, "--no-run", "--message-format=json"], stage=True)
    e = first_compiler_error(json_messages(r.stdout), tree)
    if r.returncode:
        if e and (e["package_id"] or "").startswith(sdk_url):
            return conclude(rec, "caller compile", e["rendered"], e, t, tree)
        return {**rec, "stage": "invalid: the oracle build failed outside the SDK package"}
    # 4. oracle run
    r = ctx.cargo(["test", "-p", pkg, "--test", oname, "--", "--format", "pretty"], stage=True, merge=True)
    rl = ctx.cargo(["test", "-p", pkg, "--test", oname, "--", "--list"], stage=True, merge=True)
    verdict = I4.oracle_verdict(I4.oracle_test_names(oracle), r.stdout, r.returncode,
                                I4.parse_listing(rl.stdout) if rl.returncode == 0 else [])
    rec["oracle"] = {k: verdict[k] for k in ("status", "pass", "failed", "missing", "unexpected")}
    refusal = t.get("refusal", {}).get(ctx.arm) or t.get("refusal", {}).get("*")
    if not rec["existing_tests"]["passed"]:
        blocks, _ = I4.failure_blocks(text)
        named = sorted(blocks, key=lambda b: b.splitlines()[0])
        kind = ("run-time refusal" if refusal and any(re.search(refusal, b) for b in blocks)
                else "wrong behaviour caught by the existing tests")
        return conclude(rec, kind, named[0] if named else None, None, t, tree)
    if verdict["pass"]:
        return conclude(rec, "never", None, None, t, tree)
    if verdict["status"] != "test_failed":
        return {**rec, "stage": f"invalid: oracle status {verdict['status']}"}
    blocks, _ = I4.failure_blocks(r.stdout)
    named = sorted(blocks, key=lambda b: b.splitlines()[0])
    refused = bool(refusal) and any(re.search(refusal, b) for b in blocks)
    return conclude(rec, "run-time refusal" if refused else "wrong behaviour caught by the oracle only",
                    named[0] if named else None, None, t, tree)


def conclude(rec, stage, first, error, t, tree):
    hit, matched = names_endpoint(first or "", t.get("names"))
    return {**rec, "stage": stage, "first_diagnostic": normalise(first, tree)[:4000],
            "first_code": (error or {}).get("code"), "names_endpoint": hit, "names_matched": matched}


def reference_ok(rec):
    return (rec.get("stage") == "never" and rec.get("existing_tests", {}).get("passed")
            and rec.get("oracle", {}).get("pass"))


def run_stage(t, ctx):
    """A stage task on one arm: the reference must pass (builds, existing tests and oracle pass),
    each known-bad control must fail its expectation, then the omission's detection stage is the
    measurement: pass when it is one of `expect.stages` (and names the endpoint when required)."""
    p = patches_for(t, ctx.arm)
    if not p:
        return {"verdict": "invalid", "reason": f"no patches for arm {ctx.arm}"}
    runs = {"reference": stage_variant(t, "reference", os.path.join(t["_dir"], p["reference"]), ctx)}
    if not reference_ok(runs["reference"]):
        return {"verdict": "invalid", "reason": f"the reference does not pass ({runs['reference'].get('stage')})", "runs": runs}
    for c in p.get("controls", []):
        rec = stage_variant(t, "control:" + c["name"], os.path.join(t["_dir"], c["patch"]), ctx)
        runs["control:" + c["name"]] = rec
        want_pass = c.get("expect", "fail") == "pass"
        if rec.get("stage", "").startswith("invalid") or reference_ok(rec) != want_pass:
            return {"verdict": "invalid", "reason": f"control {c['name']} did not {'pass' if want_pass else 'fail'} ({rec.get('stage')})",
                    "runs": runs}
    om = stage_variant(t, "omission", os.path.join(t["_dir"], p["omission"]), ctx)
    runs["omission"] = om
    st = om.get("stage", "")
    if st.startswith("invalid"):
        return {"verdict": "invalid", "reason": f"omission run invalid: {st}", "runs": runs}
    exp = t["expect"]
    fp = [st, om.get("names_endpoint"), om.get("first_diagnostic")]
    if st not in exp["stages"]:
        return {"verdict": "fail", "reason": f"omission detected at `{st}`, expected one of {exp['stages']}", "runs": runs,
                "stage": st, "fingerprint": fp}
    if exp.get("names_endpoint") and not om.get("names_endpoint"):
        return {"verdict": "fail", "reason": f"omission detected at `{st}`, but the first diagnostic does not name the endpoint",
                "runs": runs, "stage": st, "fingerprint": fp}
    return {"verdict": "pass", "reason": None, "runs": runs, "stage": st, "fingerprint": fp}


# ---------------------------------------------------------------- one arm

class ArmCtx:
    """Paths, provenance and the sandboxed cargo of one arm in one run."""

    def __init__(self, arm, sha, out, tasks_dir, log, jobs=None):
        self.arm, self.sha, self.tasks_dir, self.log = arm, sha, tasks_dir, log
        base = os.path.join(out, "trees")
        self.tree = os.path.join(base, f"{arm}-{sha[:12]}")
        self.stage_tree = os.path.join(base, f"{arm}-{sha[:12]}-stage")
        self.scratch = os.path.join(out, "scratch", f"{arm}-{sha[:12]}")
        os.makedirs(self.scratch, exist_ok=True)
        self.target = A.target_dir(sha, "clean")
        self.stage_target = A.target_dir(sha, "stage")
        self.jobs = jobs or os.environ.get("CARGO_BUILD_JOBS") or "4"
        self._boxes = {}

    def prepare_clean(self):
        prov = A.materialise(self.sha, self.tree)
        self.log.append({"tree": self.tree, "provenance": prov, "target": self.target})
        return prov

    def check(self, stage=False):
        A.check_tree(self.stage_tree if stage else self.tree, self.sha)
        A.check_target(self.stage_target if stage else self.target, self.sha, "stage" if stage else "clean")

    def box(self, stage):
        key = "stage" if stage else "clean"
        if key not in self._boxes:
            self._boxes[key] = S.CompileSandbox(self.stage_tree if stage else self.tree,
                                                self.stage_target if stage else self.target)
            self.log.append({"sandbox": key, **self._boxes[key].describe()})
        return self._boxes[key]

    def cargo(self, args, stage=False, merge=False):
        """cargo inside the compile sandbox on this arm's tree, after the provenance checks."""
        self.check(stage)
        box = self.box(stage)
        cmd = box.command(["cargo", args[0], "--offline", "--frozen", "-j", str(self.jobs)] + list(args[1:]))
        t0 = time.monotonic()
        r = subprocess.run(cmd, env=box.parent_env, stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT if merge else subprocess.PIPE, text=True)
        self.log.append({"cargo": args[:6], "stage": stage, "exit": r.returncode, "seconds": round(time.monotonic() - t0, 1)})
        return r
