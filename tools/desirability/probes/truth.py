FIXTURE_TYPES = {".json": "application/json", ".txt": "text/plain; charset=utf-8", ".csv": "text/csv",
                 ".tsv": "text/tab-separated-values", ".xml": "application/xml", ".atom": "application/atom+xml",
                 ".ndjson": "application/x-ndjson", ".jsonl": "application/x-ndjson", ".html": "text/html",
                 ".sse": "text/event-stream"}
GENERIC_FIXTURES = [("generic:{}", "application/json; charset=utf-8", "{}"),
                    ("generic:[]", "application/json; charset=utf-8", "[]"),
                    ("generic:empty", "", ""),
                    ("generic:text", "text/plain; charset=utf-8", "ok")]
# `-> stream T` replies (tried only for stream picks): a stream opens when its format accepts the
# reply's media type, so the SDK's fixture files are offered again under each stream media type
# (server-sent events, JSON Lines, JSON values; Mastodon's documented SSE body is a `.txt` file),
# then minimal bodies of each format
STREAM_MEDIA = ("text/event-stream", "application/x-ndjson", "application/json")
STREAM_GENERIC = [("stream:generic:sse", "text/event-stream", "event: message\ndata: {}\n\n"),
                  ("stream:generic:jsonl", "application/x-ndjson", "{}\n"),
                  ("stream:generic:json", "application/json", "{}\n")]
FIXTURE_MAX_BYTES = 512 * 1024


def sdk_fixtures(sdk, repo):
    """Candidate replies for the R3 receiver: every file under the SDK's own `fixtures/` (the
    response documents its tests use), then generic ones. [{name, content_type, path|None, body|None}]."""
    out = []
    root = os.path.join(sdk.dir, "fixtures")
    for dp, dns, fs in os.walk(root):
        dns.sort()
        for f in sorted(fs):
            p = os.path.join(dp, f)
            if os.path.getsize(p) > FIXTURE_MAX_BYTES or os.path.islink(p):
                continue
            ext = os.path.splitext(f)[1].lower()
            out.append({"name": os.path.relpath(p, repo), "content_type": FIXTURE_TYPES.get(ext, "application/octet-stream"),
                        "path": os.path.relpath(p, repo), "body": None})
    for name, ct, body in GENERIC_FIXTURES:
        out.append({"name": name, "content_type": ct, "path": None, "body": body})
    return out


ERRORISH = re.compile(r"error|malformed|invalid|fail|denied|forbidden|unauthori|not.?found|missing|bad|"
                      r"limit|throttl|conflict|(?<!\d)[45]\d\d(?!\d)", re.I)


def fixture_order(fixtures, pick):
    """Indices of `fixtures` in the order the reference tries them for one pick: files whose name
    shares words with the endpoint, its scopes or its output type first, error documents last;
    for a `-> stream` pick then the files again under the stream media types and the minimal
    stream bodies; the generic replies at the end."""
    words = set()
    for w in [pick["endpoint"]] + list(pick["scopes"]) + re.findall(r"[A-Za-z]+", pick.get("output") or ""):
        words |= {x.lower() for x in re.findall(r"[A-Z]?[a-z]+|[A-Z]+(?![a-z])", w) + w.split("_") if len(x) >= 3}
    stream = (pick.get("output") or "").strip().startswith("stream")

    def key(i):
        fx = fixtures[i]
        if fx["name"].startswith("stream:"):
            if not stream:
                return (9, 0, i)
            if not fx.get("path"):
                return (4, 0, i)
            name = os.path.basename(fx["path"]).lower()
            return (3 if ERRORISH.search(name) else 2, -sum(1 for w in words if w in name), i)
        if fx["name"].startswith("constructed:"):
            return (1, 0, i) if fx["name"].split("#")[0] == "constructed:" + (pick.get("output") or "").strip() else (9, 0, i)
        if not fx.get("path"):
            return (5, 0, i)
        name = os.path.basename(fx["path"]).lower()
        return (1 if ERRORISH.search(name) else 0, -sum(1 for w in words if w in name), i)
    return [i for i in sorted(range(len(fixtures)), key=key) if key(i)[0] != 9]


