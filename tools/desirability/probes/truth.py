"""I3 ground truth: what the implementation does for every item of a bank.

    python3 -I tools/desirability/probes/truth.py --bank tools/desirability/probes/bank
        [--sdk SHORT ..] [--harness-dir DIR] [--repo REPO]

For each SDK bank it generates one Rust unit-test module per file holding an `api!` block
(`<harness-dir>/<sdk>__<file>.rs`; default `checks/probe-truth/main/` for the main bank, else
`<bank>/harness/`), injects `#[cfg(test)] #[path = ".."] mod __concord_probe_truth;` into that
file in a throwaway copy of the repository (`target/tmp/probe-truth-copy`, never the committed
tree), compiles with `cargo test -p <pkg> --lib --no-run`, drops the generated functions that do
not compile (errors mapped to functions by line), recompiles, then runs
`cargo test -p <pkg> --lib __concord_probe_truth -- --nocapture` and parses the dump.

- wire (R1): `.prepare()` of the snippet: method, URL, headers in order, body, Content-Type and
  Accept; canary values (the strings injected for sensitive values) are replaced by `<secret>`.
- result (R2): the type `send()` resolves to, from the declaration (`send P -> Template`, plain
  `send P;` resolved through the SDK's `impl SendWith<..> for P`, or `Result<T, concord::Error>`
  without a policy), verified by the compiler (`Future<Output = TYPE>` is asserted); and for the
  `with_base_url` question, which candidate strings keep the prefix (by preparing the call).
- call (R3): a reference call (one expression, `api.<setters>.<call>.send().await`, its value bound
  to the declared send() result type, `call_binding`; for `-> stream T` the declared
  `Result<_, E>` tied to the reference's own type) compiled in the same wrapper the scorer uses
  (positive control), run against local receivers answering the SDK's fixtures (then a document
  constructed from the output type, for a stream the fixtures under each stream media type and
  minimal stream bodies, then generic replies) until one decodes or opens; that reply is the
  item's fixture, and two more runs with it give the recorded requests (method, target, headers,
  body) and the values that vary between runs.

Writes `<bank>/truth/<sdk>.json` and `<bank>/truth/drops.json`. Run Python with `-I`.
"""
