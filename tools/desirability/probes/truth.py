def inject(copy_root, modules, mod_name=MOD_NAME):
    by_file = {}
    for m in modules:
        by_file.setdefault(m.api_file, []).append(m)
    for api_file, ms in by_file.items():
        assert len(ms) == 1, api_file
        target = os.path.join(copy_root, api_file)
        text = open(target, encoding="utf-8").read()
        decl = f'\n#[cfg(test)]\n#[path = "{os.path.abspath(ms[0].path)}"]\nmod {mod_name};\n'
        at = inline_module_end(text)
        text = text + decl if at is None else text[:at] + decl + text[at:]
        with open(target, "w", encoding="utf-8") as f:
            f.write(text)


def inline_module_end(text):
    """Offset of the closing brace of the innermost inline `mod x { .. }` that holds the file's
    first `api!` block (the generated items live there), or None at file level."""
    from static_scan import api_spans, match_brace
    clean = C.strip_strings_and_comments(text)
    spans = api_spans(text, clean)
    if not spans:
        return None
    s0 = spans[0][0]
    best = None
    for m in re.finditer(r"\bmod\s+\w+\s*\{", clean):
        ob = m.end() - 1
        cb = match_brace(clean, ob)
        if ob < s0 < cb and (best is None or ob > best[0]):
            best = (ob, cb)
    return best[1] if best else None


def write_modules(modules):
    spans = {}
    for m in modules:
        src, sp = m.render()
        os.makedirs(os.path.dirname(m.path), exist_ok=True)
        with open(m.path, "w", encoding="utf-8") as f:
            f.write(src)
        spans[os.path.realpath(m.path)] = sp
    return spans


def _span_files(span, acc):
    acc.append(span)
    exp = span.get("expansion")
    if exp and exp.get("span"):
        _span_files(exp["span"], acc)


def map_error(msg, spans):
    """The block tag an error message belongs to, or None."""
    cands = []
    for sp in msg.get("spans", []):
        chain = []
        _span_files(sp, chain)
        for s in chain:
            cands.append((not sp.get("is_primary"), s))
    for child in msg.get("children", []):
        for sp in child.get("spans", []):
            cands.append((True, sp))
    cands.sort(key=lambda x: x[0])
    for _, s in cands:
        f = os.path.realpath(s.get("file_name", ""))
        if f in spans:
            line = s.get("line_start", 0)
            for tag, (a, b) in spans[f].items():
                if a <= line <= b:
                    return tag
    return None


def cargo(copy_root, args, capture=True, timeout=None, extra_env=None):
    """cargo on the host with the inherited environment (trusted code only: truth harnesses; the
    scorer compiles reader answers inside bubblewrap instead, see score.py `CompileSandbox`)."""
    env = C.cargo_env()
    # Requests that do not go to the local receiver are sent to a closed local port (reqwest
    # reads proxy variables), so nothing reaches a real provider.
    for k in ("HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "http_proxy", "https_proxy", "all_proxy"):
        env[k] = "http://127.0.0.1:9"
    env["NO_PROXY"] = env["no_proxy"] = "127.0.0.1,localhost"
    env.update(extra_env or {})
    return subprocess.run(["cargo"] + args, cwd=copy_root, env=env, capture_output=capture,
                          text=True, timeout=timeout)


def compile_rounds(copy_root, modules, log, max_rounds=60, artifacts=None, runner=None):
    """Compile until every remaining block builds. Returns {tag: first error line}. `artifacts`
    (a dict) receives {package name: unit-test executable} from the last build. `runner(copy_root,
    args)` runs cargo (default: `cargo` on the host)."""
    failed = {}
    runner = runner or cargo
    for rnd in range(max_rounds):
        modules_live = [m for m in modules if m.blocks]
        spans = write_modules(modules)
        pkgs = sorted({m.pkg for m in modules_live})
        if not pkgs:
            break
        args = ["test", "--lib", "--no-run", "--no-fail-fast", "--message-format=json"]
        for p in pkgs:
            args += ["-p", p]
        r = runner(copy_root, args)
        errors_by_tag, unmapped = {}, Counter()
        for line in r.stdout.splitlines():
            try:
                ev = json.loads(line)
            except ValueError:
                continue
            if artifacts is not None and ev.get("reason") == "compiler-artifact" and ev.get("executable") \
                    and (ev.get("profile") or {}).get("test") and "lib" in (ev.get("target") or {}).get("kind", []):
                pid = ev.get("package_id", "")
                tname = (ev.get("target") or {}).get("name")
                for p in pkgs:
                    if f"#{p}@" in pid or pid.startswith(p + " ") or tname == p.replace("-", "_"):
                        artifacts[p] = ev["executable"]
            if ev.get("reason") != "compiler-message":
                continue
            msg = ev["message"]
            if msg.get("level") not in ("error", "error: internal compiler error"):
                continue
            if msg.get("message", "").startswith("aborting due to") or \
                    re.match(r"could not compile", msg.get("message", "")):
                continue
            tag = map_error(msg, spans)
            text = msg.get("message", "")
            code = (msg.get("code") or {}).get("code")
            if code:
                text = f"{code}: {text}"
            if tag:
                errors_by_tag.setdefault(tag, text)
            else:
                pkg = ev.get("package_id", "?")
                unmapped[(pkg, text)] += 1
        log.append({"round": rnd, "packages": len(pkgs), "exit": r.returncode,
                    "mapped_errors": len(errors_by_tag), "unmapped_errors": len(unmapped)})
        if r.returncode == 0 and not errors_by_tag:
            break
        if not errors_by_tag:
            # a failure we cannot attribute to a block: report and give up on those packages
            bad_pkgs = {pk for (pk, _) in unmapped}
            first = next(iter(unmapped), ("?", r.stderr.strip().splitlines()[-1:] or ["?"]))
            for m in modules_live:
                if any(m.pkg in pk or pk == "?" for pk in bad_pkgs) or not bad_pkgs:
                    for tag, _ in m.blocks:
                        failed[tag] = f"unattributed compile error: {first[1]}"
                    m.blocks = []
            if not unmapped:
                log.append({"stderr_tail": r.stderr[-2000:]})
            continue
        failed.update(errors_by_tag)
        for m in modules:
            for t in m.drop(set(errors_by_tag)):
                failed.setdefault(t, "needs a block that does not compile")
    return failed


def run_tests(copy_root, modules, mod_name=MOD_NAME):
    pkgs = sorted({m.pkg for m in modules if m.blocks})
    if not pkgs:
        return [], ""
    args = ["test", "--lib", "--no-fail-fast"]
    for p in pkgs:
        args += ["-p", p]
    args += [mod_name, "--", "--nocapture", "--test-threads=8"]
    r = cargo(copy_root, args, timeout=3600)
    recs = []
    dec = json.JSONDecoder()
    for line in r.stdout.splitlines():
        # libtest may print `test x ... ` before a dump on the same line (parallel tests)
        pos = line.find("@@PROBE ")
        while pos >= 0:
            try:
                obj, end = dec.raw_decode(line, pos + len("@@PROBE "))
                recs.append(obj)
            except ValueError:
                end = pos + 1
            pos = line.find("@@PROBE ", end)
    return recs, r.stderr[-3000:] if r.returncode else ""


