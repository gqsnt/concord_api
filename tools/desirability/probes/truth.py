def _snake(n):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", n).lower()


def _members(text, open_at):
    """[(attribute text, member text)] of a struct/enum body starting at `open_at` (the `{`)."""
    clean = C.strip_strings_and_comments(text)
    close = C.match_brace(clean, open_at)
    out, depth, start = [], 0, open_at + 1
    for i in range(open_at + 1, close + 1):
        ch = clean[i]
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}" and not (ch == ">" and clean[i - 1] in "-="):
            depth -= 1
        if (ch == "," and depth == 0) or i == close:
            raw, cl = text[start:i], clean[start:i]
            attrs = " ".join(m.group(0) for m in re.finditer(r"#\[[^\]]*\]", re.sub(r"(?m)^\s*//.*$", "", raw)))
            body = re.sub(r"#\[[^\]]*\]", " ", cl).strip()
            if body:
                out.append((attrs, body))
            start = i + 1
    return out


def _manual_deserialize(sdk, name):
    """The first word-like string literal in a hand-written `impl Deserialize for name` (a tag
    such as `"list"`), "x" when it has none, or None without such an impl."""
    for im in sdk.impls:
        if re.match(r"impl\s*<[^>]*>\s*(?:[\w:]*::)?Deserialize\s*<[^>]*>\s*for\s+" + re.escape(name) + r"\b", im["header"]):
            lit = re.search(r'"([A-Za-z_][\w.-]*)"', im["text"])
            return lit.group(1) if lit else "x"
    return None


def sample_json(sdk, type_text, depth=0, subst=None, truth_value=False):
    """A JSON value of the Rust type (SDK structs and enums followed through their serde
    attributes; booleans `truth_value`; a type it cannot see is guessed to be a string), or
    raises ValueError when the type is not simple enough."""
    if depth > 8:
        raise ValueError("too deep")
    t = C.parse_type(sdk.resolve_alias(type_text))
    subst = subst or {}
    if t[0] == "tuple":
        return [sample_json(sdk, C.type_str(x), depth + 1, subst, truth_value) for x in t[1]]
    if t[0] == "ref":
        return sample_json(sdk, C.type_str(t[2]), depth + 1, subst, truth_value)
    if t[0] != "path":
        raise ValueError(C.type_str(t))
    last, args = t[1][-1], [C.type_str(x) for x in t[2]]
    if len(t[1]) == 1 and last in subst:
        return sample_json(sdk, subst[last], depth + 1, None, truth_value)
    if last in ("String", "str", "Cow", "Url", "PathBuf"):
        return "x"
    if last in C.PRIM_INT or last in C.NONZERO or last == "NonZero":
        return 1
    if last in C.PRIM_FLOAT:
        return 1.0
    if last == "bool":
        return truth_value
    if last == "Option" or last == "Value":
        return None
    if last in ("Vec", "VecDeque", "HashSet", "BTreeSet", "Bytes"):
        return []
    if last in ("HashMap", "BTreeMap", "IndexMap", "Map"):
        return {}
    if last in ("Box", "Arc", "Rc") and args:
        return sample_json(sdk, args[0], depth + 1, subst, truth_value)
    manual = _manual_deserialize(sdk, last)
    if manual is not None:
        return manual
    it = sdk.find(last, ("struct", "enum"))
    if it is None:
        return "x"  # a type defined by a macro or another crate: most are identifiers
    text, clean = it["text"], C.strip_strings_and_comments(it["text"])
    km = re.search(r"\b(struct|enum)\s+" + re.escape(last) + r"\s*(<([^>{]*)>)?", clean)
    head_attrs = " ".join(re.findall(r"#\[serde\(([^\]]*)\)\]", text[:km.start()]))
    params = [g.strip().split(":")[0].strip() for g in C.split_generics(km.group(3) or "")
              if g.strip() and not g.strip().startswith("'")]
    sub = {p: (args[i] if i < len(args) else "()") for i, p in enumerate(params)}
    rename_all = _serde_attr(head_attrs, "rename_all")
    if re.search(r"\b(untagged|tag|content|remote|try_from|from)\b", head_attrs):
        raise ValueError(f"{last}: serde representation not simple")
    after = clean[km.end():]
    if km.group(1) == "struct":
        if re.match(r"\s*\(", after) or re.search(r"\btransparent\b", head_attrs):
            inner = re.match(r"\s*\((.*)\)\s*;", after, re.S)
            if not inner:
                raise ValueError(f"{last}: tuple struct")
            fields = C.split_generics(inner.group(1))
            vals = [sample_json(sdk, re.sub(r"^pub(\([^)]*\))?\s+", "", f), depth + 1, sub, truth_value) for f in fields]
            return vals[0] if len(vals) == 1 else vals
        if re.match(r"\s*;", after):
            return None
        obj = {}
        for attrs, body in _members(text, km.end() + after.index("{")):
            fm = re.match(r"(?:pub(?:\([^)]*\))?\s+)?(?:r#)?(\w+)\s*:\s*(.+)$", body, re.S)
            if not fm:
                raise ValueError(f"{last}: field {body[:40]}")
            name, ftype = fm.group(1), fm.group(2).strip()
            sattrs = " ".join(re.findall(r"#\[serde\(([^\]]*)\)\]", attrs))
            if re.search(r"\bskip(_deserializing)?\b", sattrs):
                continue
            val = sample_json(sdk, ftype, depth + 1, sub, truth_value)
            if re.search(r"\bflatten\b", sattrs):
                if isinstance(val, dict):
                    obj.update(val)
                continue
            key = _serde_attr(sattrs, "rename") or (_RENAME.get(rename_all, lambda n: n)(name))
            obj[key] = val
        return obj
    # enum: the first unit variant, as its serialized name
    for attrs, body in _members(text, km.end() + after.index("{")):
        vm = re.match(r"(\w+)\s*(=.*)?$", body, re.S)
        sattrs = " ".join(re.findall(r"#\[serde\(([^\]]*)\)\]", attrs))
        if vm and not re.search(r"\b(skip|skip_deserializing|other)\b", sattrs):
            ren = _serde_attr(sattrs, "rename")
            if ren:
                return ren
            n = vm.group(1)
            return _RENAME[rename_all](_snake(n)) if rename_all in _RENAME and rename_all != "PascalCase" else n
    raise ValueError(f"{last}: no unit variant")


def constructed_fixtures(sdk, pick):
    """Documents built from the pick's output type: booleans false, then true (a provider flag
    such as Slack's `ok`)."""
    out = (pick.get("output") or "").strip()
    if not out or out.startswith("stream"):
        return []
    docs = []
    for tv in (False, True):
        try:
            body = json.dumps(sample_json(sdk, out, truth_value=tv), separators=(",", ":"))
        except (ValueError, IndexError, KeyError, TypeError, AttributeError):
            return []
        if all(body != d["body"] for d in docs):
            docs.append({"name": f"constructed:{out}#{'true' if tv else 'false'}", "content_type": "application/json",
                         "path": None, "body": body})
    return docs


def fixture_expr(fx, module_path, repo):
    """A Rust `__Fixture` literal; a file is embedded with `include_bytes!` relative to the module."""
    if fx.get("path"):
        rel = os.path.relpath(os.path.join(repo, fx["path"]), os.path.dirname(os.path.abspath(module_path)))
        body = f"include_bytes!({C.rust_str(rel)})"
    else:
        body = "b" + C.rust_str(fx["body"] or "")
    return f"__Fixture {{ name: {C.rust_str(fx['name'])}, content_type: {C.rust_str(fx['content_type'])}, body: {body} }}"


def fixtures_static(fixtures, module_path, repo):
    return ("static __FIXTURES: &[__Fixture] = &[\n"
            + "".join(f"    {fixture_expr(fx, module_path, repo)},\n" for fx in fixtures) + "];")


def wrap_call_fn(name, client, body, binding, ok_form=False, reference=None):
    """The wrapper the R3 scorer pastes an answer into (and the truth's reference call). `body` is
    the answer, one expression whose value is the public `send().await` result. With a declared
    type (`binding["type"]`, the R2 truth) the value is bound to it, so a value of any other type
    (`()`, an `Option` from `.ok()`, a raw response) does not compile; for a `Result`
    (`binding["result"] == "is_ok"`) the wrapper returns `Ok(())` only when the value is `Ok`.
    With `binding["same_as"] == "reference"` (`-> stream T`, whose declared type is `Result<_, E>`)
    the value is also tied to the type of `reference`'s own `send().await` (type-checked in a
    branch that never runs, on a clone of the client). `ok_form`: the compatibility path for a
    body ending in `.send().await?`, whose value must then be the declared result's `Ok` type (the
    `?` returns the error from the wrapper). Without a declared type the value is bound unchecked."""
    ty = binding.get("type")
    witness = binding.get("same_as") == "reference" and reference
    head = f"async fn {name}(api: {client}) -> ::core::result::Result<(), ::std::boxed::Box<dyn ::std::error::Error>> {{\n"
    pre = ""
    if witness:
        pre = ("let mut __w = ::core::option::Option::None;\n"
               "if false {\n    let api = ::core::clone::Clone::clone(&api);\n"
               f"    __w = ::core::option::Option::Some({{\n{reference}\n}});\n}}\n")
    annot = f": {ty}" if ty else ""
    if ty and ok_form:
        bind = f"let __r{annot} = ::core::result::Result::Ok({{\n{body}\n}});\n"
    else:
        bind = f"let __r{annot} = {{\n{body}\n}};\n"
    if witness:
        bind += "__probe_same_type(&__w, &__r);\n"
    tail = "__probe_outcome(&__r)\n}" if ty and binding.get("result") == "is_ok" else "let _ = &__r;\n::core::result::Result::Ok(())\n}"
    return head + pre + bind + tail


def bank_fixtures(bank, sdk, repo):
    """The SDK's fixture files, one document constructed from each picked output type, the
    generic replies."""
    fixtures = sdk_fixtures(sdk, repo)
    seen = set()
    for pick in bank["picks"]:
        for fx in constructed_fixtures(sdk, pick):
            if fx["name"] not in seen:
                seen.add(fx["name"])
                fixtures.insert(len(fixtures) - len(GENERIC_FIXTURES), fx)
    if any((p.get("output") or "").strip().startswith("stream") for p in bank["picks"]):
        files = [fx for fx in fixtures if fx.get("path")]
        extra = [{"name": f"stream:{fx['name']}#{media}", "content_type": media, "path": fx["path"], "body": None}
                 for fx in files for media in STREAM_MEDIA]
        extra += [{"name": n, "content_type": ct, "path": None, "body": body} for n, ct, body in STREAM_GENERIC]
        at = len(fixtures) - len(GENERIC_FIXTURES)
        fixtures[at:at] = extra
    return fixtures


def build_modules(bank, sdk, harness_dir, r2s, repo=C.REPO):
    mods = {}
    fixtures = bank_fixtures(bank, sdk, repo)
    for item in bank["items"]:
        pick = bank["picks"][item["pick"]]
        api_file = pick["client_file"]
        key = (bank["pkg"], api_file)
        if key not in mods:
            stem = os.path.splitext(os.path.basename(api_file))[0]
            path = os.path.join(harness_dir, f"{bank['short']}__{stem}.rs")
            mods[key] = Module(bank["pkg"], api_file, path,
                               header("truth.py", f"ground truth for `{bank['short']}` ({api_file})", sdk.dir)
                               + "\n" + fixtures_static(fixtures, path, repo) + "\n")
        m = mods[key]
        iid = item["id"]
        n = iid.rsplit("/", 1)[1]
        ctor, call = pick["rust"]["client"], pick["rust"]["call"]
        client = next(c for c, _ in sdk.clients if c["name"] == pick["client"])
        bpath = base_path_of(client["stmts"]["base"])
        if item["kind"] == "wire":
            m.add(f"{iid}#wire", f"#[test]\nfn __probe_{n}() {{\n    let api = {ctor};\n    let call = {call};\n"
                                 f"    __dump({C.rust_str(iid)}, \"wire\", \"\", call.prepare());\n}}")
            if item.get("boundary") == "operation":
                m.add(f"{iid}#op", record_block(f"__probe_{n}_op", iid, "op", ctor, bpath,
                                                f"let call = {call};\n        let _ = call.send().await;\n        None"))
        elif item["kind"] == "result":
            r2 = r2s[iid]
            if r2.get("resolvable"):
                m.add(f"{iid}#type", f"fn __probe_{n}_type(api: {pick['client']}) {{\n    let call = {call};\n"
                                     f"    let fut = call.send();\n    __assert_output::<_, {r2['send_returns']}>(&fut);\n}}")
            bq = item.get("base_url")
            if bq:
                cands = ", ".join(C.rust_str(c) for c in bq["candidates"])
                m.add(f"{iid}#base", f"#[test]\nfn __probe_{n}_base() {{\n    let api0 = {ctor};\n"
                                     f"    {{ let api = api0.clone(); let call = {call}; __dump({C.rust_str(iid)}, \"base\", \"\", call.prepare()); }}\n"
                                     f"    for cand in [{cands}] {{\n"
                                     f"        match api0.clone().with_base_url(cand) {{\n"
                                     f"            Ok(api) => {{ let call = {call}; __dump({C.rust_str(iid)}, \"base\", cand, call.prepare()); }}\n"
                                     f"            Err(e) => __dump_err({C.rust_str(iid)}, \"base\", cand, &format!(\"{{:?}}\", e.kind())),\n"
                                     f"        }}\n    }}\n}}")
        elif item["kind"] == "call":
            ref = reference_call(bank, pick)
            m.add(f"{iid}#ref", wrap_call_fn(f"__probe_{n}_ref", pick["client"], ref,
                                             call_binding(r2s[iid.replace("/c", "/r")]), reference=ref))
            bare = bank["clients"][pick["client"]]["ctor"]
            # the reference runs against the SDK's fixtures until one decodes (the result check),
            # then twice more with that reply: values that differ between the passes are volatile
            order = ", ".join(f"__FIXTURES[{i}]" for i in fixture_order(fixtures, pick))
            m.add(f"{iid}#refrun", record_block(f"__probe_{n}_refrun", iid, "r3", bare, bpath,
                                                outcome_of(f"__probe_{n}_ref(api)"), f"&[{order}]", 2),
                  needs=f"{iid}#ref")
    return list(mods.values())


