def r2_truth(sdk, pick):
    """{"resolvable", "reason", "send_returns", "error_type"} from the declaration."""
    client = next(c for c, _ in sdk.clients if c["name"] == pick["client"])
    out = (pick.get("output") or "").strip()
    if re.match(r"stream\b", out):
        if out != "stream":
            # the declaration still gives the outer type when it is a `Result`: `Result<_, E>`
            # with `_` the format's reader (R3 binds that, the reader inferred from the reference)
            send = client["stmts"]["send"]
            partial = "Result<_, concord::Error>" if not send else (send.split("->", 1)[1].strip() if "->" in send else None)
            pt = C.parse_type(partial) if partial else None
            if not (pt and pt[0] == "path" and pt[1][-1] == "Result" and len(pt[2]) == 2 and pt[2][0] == ("infer",)):
                partial = None
            return {"resolvable": False, "reason": "`-> stream T`: the reader type is the format's, not in the declaration",
                    "stream": True, "partial": partial}
        out = "concord::Incoming"  # `-> stream` without an item: the unread body (cheat sheet)
    T = out or "()"
    send = client["stmts"]["send"]
    if not send:
        ty = f"Result<{T}, concord::Error>"
        return {"resolvable": True, "send_returns": ty, "error_type": "concord::Error", "how": "no send policy"}
    if "->" in send:
        tmpl = send.split("->", 1)[1].strip()
        ty = C.type_str(C.substitute(C.parse_type(tmpl), {"_": C.parse_type(T)}))
        how = "send template"
    else:
        P = send.strip()
        cp = next((p for p in client["params"] if p.get("name") == P), None)
        ptype = cp["type"] if cp else P
        plast = C.parse_type(ptype)
        plast = plast[1][-1] if plast[0] == "path" else ptype
        target = C.parse_type(T)
        matches, macro = [], False
        for gens, arg, self_ty, output, in_macro in sdk.sendwith_impls():
            st = C.parse_type(self_ty)
            if st[0] != "path" or st[1][-1] != plast:
                continue
            if in_macro or output is None:
                macro = True
                continue
            binding = {}
            if C.unify(C.parse_type(arg), target, set(gens), binding):
                matches.append((output, binding))
        if len(matches) != 1:
            why = ("SendWith impl generated by a macro" if macro and not matches else
                   f"{len(matches)} matching `impl SendWith<{T}> for {plast}`")
            return {"resolvable": False, "reason": f"plain `send {P};`: {why}"}
        output, binding = matches[0]
        ty = C.type_str(C.substitute(C.parse_type(output), binding))
        how = f"impl SendWith for {plast}"
    t = C.parse_type(sdk.resolve_alias(ty))
    err = None
    if t[0] == "path" and t[1][-1] == "Result" and len(t[2]) == 2:
        err = C.type_str(t[2][1])
    return {"resolvable": True, "send_returns": ty, "error_type": err, "how": how}


def reference_call(bank, pick):
    """The reference answer under the R3 contract: one expression whose value is the public
    `send().await` result (client setters chained on `api`, then the call; no `?`, no `;`)."""
    ctor = bank["clients"][pick["client"]]["ctor"]
    setters = pick["rust"]["client"][len(ctor):]
    call = pick["rust"]["call"]
    assert call.startswith("api."), call
    return f"api{setters}{call[len('api'):]}.send().await"


def call_binding(r2):
    """How the R3 wrapper binds a call's value (see `wrap_call_fn`): the declared `send()` result
    type from the R2 truth, and whether its success is checked (`is_ok`, for a `Result`). For
    `-> stream T` whose declared outer type is `Result<_, E>`, the value is bound to that and to
    the reference call's own result type (`same_as`), and checked with `is_ok` (the stream opened)."""
    if not r2.get("resolvable"):
        if r2.get("stream") and r2.get("partial"):
            return {"type": r2["partial"], "result": "is_ok", "same_as": "reference",
                    "note": "`-> stream T`: the reader type is the format's; the value is bound to the declared "
                            f"`{r2['partial']}` and to the reference call's own send() result type, and must be `Ok` "
                            "(the stream opened with the item's reply)"}
        return {"type": None, "result": None,
                "reason": "the send() result type is not resolvable from the declaration: " + (r2.get("reason") or "?")}
    if r2.get("error_type"):
        return {"type": r2["send_returns"], "result": "is_ok"}
    return {"type": r2["send_returns"], "result": None, "reason": "the declared send() result is not a Result"}


# ---------------------------------------------------------------- harness building

class Module:
    """One generated module injected into one SDK source file."""

    def __init__(self, pkg, api_file, path, header):
        self.pkg, self.api_file, self.path, self.header = pkg, api_file, path, header
        self.blocks = []  # (tag, code)
        self.deps = {}    # tag -> tag it needs (dropped together)

    def add(self, tag, code, needs=None):
        self.blocks.append((tag, code))
        if needs:
            self.deps[tag] = needs

    def render(self):
        """Source text and {tag: (first line, last line)}."""
        lines = self.header.rstrip("\n").split("\n")
        spans = {}
        for tag, code in self.blocks:
            lines.append("")
            first = len(lines) + 1
            lines += code.rstrip("\n").split("\n")
            spans[tag] = (first, len(lines))
        return "\n".join(lines) + "\n", spans

    def drop(self, tags):
        """Drop `tags` and every block that needs one of them; returns the dependents dropped."""
        tags = set(tags)
        extra = {t for t, need in self.deps.items() if need in tags and t not in tags}
        self.blocks = [(t, c) for t, c in self.blocks if t not in tags | extra]
        return extra


def base_path_of(base):
    return re.sub(r"^\w+://[^/]*", "", base or "").rstrip("/")


def record_block(fn, iid, part, ctor, base_path, body, fixtures="&[__EMPTY_JSON]", passes=1):
    """A test that builds the client against local receivers answering `fixtures` (see
    `__record_with`) and runs `body` with `api`; `body` evaluates to the outcome (`None` when
    the call succeeded, else `Some(error text)`)."""
    return (f"#[test]\nfn {fn}() {{\n"
            f"    __record_with({C.rust_str(iid)}, {C.rust_str(part)}, {C.rust_str(base_path)}, {fixtures}, {passes}, "
            f"|base: String| async move {{\n"
            f"        let api = match ({ctor}).with_base_url(base.as_str()) {{\n"
            f"            Ok(api) => api,\n"
            f"            Err(e) => return Some(format!(\"with_base_url: {{:?}}\", e.kind())),\n"
            f"        }};\n"
            f"        {body}\n"
            f"    }});\n}}")


def outcome_of(call_expr):
    """Rust expression: the outcome of awaiting a wrapper (`None` on `Ok`)."""
    return f"match {call_expr}.await {{ Ok(()) => None, Err(e) => Some(e.to_string()) }}"


