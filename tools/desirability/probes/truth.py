def testserver_crate(sdk_dir):
    """The crate name under which the SDK's dev-dependencies name `concord-example-testserver`."""
    text = C.cargo_toml(sdk_dir)
    dev = text.split("[dev-dependencies]", 1)[1].split("\n[", 1)[0] if "[dev-dependencies]" in text else ""
    for line in dev.splitlines():
        m = re.match(r"\s*([\w-]+)\s*=\s*\{[^}]*package\s*=\s*\"concord-example-testserver\"", line)
        if m:
            return m.group(1).replace("-", "_")
    return "concord_example_testserver"


