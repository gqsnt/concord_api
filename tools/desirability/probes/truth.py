def mask(s, canaries):
    for c in canaries:
        s = s.replace(c, "<secret>")
    return s


def is_json_media(ct):
    if not ct:
        return False
    base = ct.split(";")[0].strip().lower()
    return base == "application/json" or base.endswith("+json")


def wire_truth(rec, canaries):
    if "error" in rec:
        return None, f"prepare() error: {rec['error']}"
    headers, secret_names = [], []
    for k, v in rec["headers"]:
        if any(c in v for c in canaries):
            headers.append([k, "<secret>"])
            secret_names.append(k)
        else:
            headers.append([k, v])
    def first(name):
        return next((v for k, v in headers if k == name), None)
    ct, acc = first("content-type"), first("accept")
    body, kind = None, None
    if rec.get("body_present"):
        if rec.get("body") is None:
            return None, "body present but not inspectable (streaming body)"
        text = mask(rec["body"], canaries)
        if is_json_media(ct):
            try:
                body, kind = json.loads(text), "json"
            except ValueError:
                body, kind = text, "text"
        else:
            body, kind = text, "text"
    return {"method": rec["method"], "url": mask(rec["url"], canaries), "headers": headers,
            "secret_headers": secret_names, "body": body, "body_kind": kind,
            "content_type": ct, "accept": acc}, None


CLIENT_ADDED = {"host", "content-length", "transfer-encoding", "connection", "accept-encoding"}


def exchanges(by_id, iid, part, nonce=""):
    """What `__record_with` dumped for one block: ({pass: {"requests", "outcome", "done",
    "fixture", "summary"}}, [(fixture tried, outcome)]). Lines with another nonce are ignored."""
    passes, tries = {}, []
    for r in by_id.get(iid, []):
        if r.get("part") != part or r.get("nonce", "") != nonce:
            continue
        if "try" in r:
            tries.append((r["try"], r.get("outcome")))
            continue
        if "pass" not in r:
            continue
        p = passes.setdefault(r["pass"], {"requests": [], "outcome": None, "done": True,
                                          "fixture": r.get("fixture"), "summary": False})
        if r.get("summary"):
            p.update(outcome=r.get("outcome"), done=r.get("done"), summary=True, of=r.get("of"))
        elif r.get("n", -1) >= 0:
            p["requests"].append(r)
    for p in passes.values():
        p["requests"].sort(key=lambda r: r["n"])
    return passes, tries


def recordings(by_id, iid, part):
    """(requests of the first exchange in order, error text or None) recorded for one block."""
    passes, _ = exchanges(by_id, iid, part)
    p = passes.get(0)
    if p is None or not p["summary"]:
        return (p or {}).get("requests", []), "the recorder printed nothing (or did not finish)"
    err = None
    if not p["done"]:
        err = "timed out after 10 s"
    elif not p["requests"] and p["outcome"]:
        err = p["outcome"]
    return p["requests"], err


R3_CLIENT_ADDED = {"host", "content-length", "transfer-encoding", "connection", "accept-encoding"}


def req_record(r, canaries):
    """A recorded request as the R3 check compares it: method, target, the headers other than the
    connection-level ones the HTTP client adds (host, content-length, transfer-encoding,
    connection, accept-encoding), in order, and the body; canaries become `<secret>`."""
    return {"method": r["method"], "target": mask(r["target"], canaries),
            "headers": [[k, mask(v, canaries)] for k, v in r["headers"] if k.lower() not in R3_CLIENT_ADDED],
            "body": mask(r.get("body") or "", canaries)}


def header_groups(rec):
    """{lower-case name: [values in order]} of a `req_record`."""
    out = {}
    for k, v in rec["headers"]:
        out.setdefault(k.lower(), []).append(v)
    return out


def volatility(a, b):
    """Compare two recordings of the same reference call (each a list of `req_record`): which
    header names and which request bodies differ between them (signatures, nonces, dates)."""
    if len(a) != len(b) or any(x["method"] != y["method"] or x["target"] != y["target"] for x, y in zip(a, b)):
        return {"sequence_differs": True, "headers": [], "bodies": []}
    hdr, bodies = set(), []
    for i, (x, y) in enumerate(zip(a, b)):
        hx, hy = header_groups(x), header_groups(y)
        hdr |= {k for k in set(hx) | set(hy) if hx.get(k) != hy.get(k)}
        if x["body"] != y["body"]:
            bodies.append(i)
    return {"sequence_differs": False, "headers": sorted(hdr), "bodies": bodies}


def operation_truth(rec, prepared, canaries):
    """Wire truth from a request the local receiver recorded (the public `send()`), in the same
    shape as `wire_truth`. Headers the HTTP client adds on its own are left out: host,
    content-length, transfer-encoding, connection, accept-encoding, and `accept: */*` when the
    prepared request had no `accept`."""
    prep_names = {k for k, _ in prepared["headers"]} if prepared else set()
    headers, secret = [], []
    for k, v in rec["headers"]:
        if k in CLIENT_ADDED or (k == "accept" and v == "*/*" and "accept" not in prep_names):
            continue
        if any(c in v for c in canaries):
            headers.append([k, "<secret>"])
            secret.append(k)
        else:
            headers.append([k, v])
    first = lambda name: next((v for k, v in headers if k == name), None)  # noqa: E731
    ct, acc = first("content-type"), first("accept")
    origin = re.match(r"^(\w+://[^/]+)", prepared["url"]).group(1) if prepared else "http://unknown"
    text = mask(rec.get("body") or "", canaries)
    body, kind = None, None
    if text or ct:
        if is_json_media(ct):
            try:
                body, kind = json.loads(text), "json"
            except ValueError:
                body, kind = text, "text"
        else:
            body, kind = text, "text"
    return {"method": rec["method"], "url": mask(origin + rec["target"], canaries), "headers": headers,
            "secret_headers": secret, "body": body, "body_kind": kind, "content_type": ct, "accept": acc}


def same_request(a, b):
    if not a or not b:
        return False
    return (a["method"] == b["method"] and a["url"] == b["url"] and a["body"] == b["body"]
            and sorted(map(tuple, a["headers"])) == sorted(map(tuple, b["headers"])))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--bank", required=True)
    ap.add_argument("--sdk", nargs="*")
    ap.add_argument("--harness-dir")
    ap.add_argument("--repo", default=C.REPO)
    a = ap.parse_args()
    bank_dir = os.path.abspath(a.bank)
    repo = os.path.abspath(a.repo)
    if a.harness_dir:
        harness_dir = os.path.abspath(a.harness_dir)
    elif os.path.realpath(bank_dir) == os.path.realpath(C.MAIN_BANK):
        harness_dir = os.path.join(repo, "checks", "probe-truth", "main")
    else:
        harness_dir = os.path.join(bank_dir, "harness")
    banks = []
    for f in sorted(os.listdir(bank_dir)):
        if f.endswith(".json") and f != "index.json":
            b = C.read_json(os.path.join(bank_dir, f))
            if not a.sdk or b["short"] in a.sdk:
                banks.append(b)
    os.makedirs(harness_dir, exist_ok=True)
    for f in os.listdir(harness_dir):
        if f.endswith(".rs") and (not a.sdk or f.split("__")[0] in a.sdk):
            os.remove(os.path.join(harness_dir, f))
    sdks, r2s, modules, fixtures_of = {}, {}, [], {}
    for b in banks:
        sdk = C.Sdk(os.path.join(repo, "examples", b["sdk"]), repo)
        sdks[b["short"]] = sdk
        fixtures_of[b["short"]] = bank_fixtures(b, sdk, repo)
        for item in b["items"]:
            if item["kind"] == "result":
                r2s[item["id"]] = r2_truth(sdk, b["picks"][item["pick"]])
        modules += build_modules(b, sdk, harness_dir, r2s, repo)
    copy_root = C.scratch_copy(repo, "probe-truth-copy")
    inject(copy_root, modules)
    log = []
    failed = compile_rounds(copy_root, modules, log)
    write_modules(modules)
    recs, run_err = run_tests(copy_root, modules)
    by_id = {}
    for r in recs:
        by_id.setdefault(r["id"], []).append(r)
    drops = []
    totals = Counter()
    for b in banks:
        sdk = sdks[b["short"]]
        out = {"sdk": b["sdk"], "short": b["short"], "pkg": b["pkg"], "repo_head": git_head(repo),
               "truth_format": TRUTH_FORMAT, "aliases": C.accepted_aliases(sdk), "items": {}, "drops": []}
        for item in b["items"]:
            iid, pick = item["id"], b["picks"][item["pick"]]
            canaries = pick["canaries"]
            t, reason = None, None
            if item["kind"] == "wire":
                if f"{iid}#wire" in failed:
                    reason = "does not compile: " + failed[f"{iid}#wire"]
                else:
                    recs_w = [r for r in by_id.get(iid, []) if r["part"] == "wire"]
                    if not recs_w:
                        reason = "no dump (test did not run)" + (f": {run_err[-300:]}" if run_err else "")
                    else:
                        t, reason = wire_truth(recs_w[0], canaries)
                if item.get("boundary") == "operation" and t is not None:
                    prepared = t
                    reqs, err = recordings(by_id, iid, "op")
                    if f"{iid}#op" in failed:
                        t, reason = None, "operation truth not available: " + failed[f"{iid}#op"]
                    elif not reqs:
                        t, reason = None, "operation truth not available: no request reached the local receiver" + (f" ({err})" if err else "")
                    elif len(reqs) > 1:
                        t, reason = None, f"operation truth not available: the public send() made {len(reqs)} requests"
                    else:
                        t = operation_truth(reqs[0], prepared, canaries)
                        t["prepared"] = prepared
                        t["policy_changes_request"] = not same_request(t, prepared)
                        t["operation_completed_within_10s"] = reqs[0].get("done")
                if t is not None:
                    t["boundary"] = item.get("boundary", "prepared")
            elif item["kind"] == "result":
                r2 = dict(r2s[iid])
                if r2.get("resolvable"):
                    if f"{iid}#type" in failed:
                        r2["verified"] = False
                        r2["reason"] = "type assertion does not compile: " + failed[f"{iid}#type"]
                    else:
                        r2["verified"] = True
                        ctx = sdk.decl_module(pick["client_file"])
                        r2["decl_module"] = "::".join(("crate",) + ctx)
                        r2["send_returns_canon"] = C.canon_type(r2["send_returns"], sdk, ctx=ctx)
                        r2["error_type_canon"] = C.canon_type(r2["error_type"], sdk, ctx=ctx) if r2.get("error_type") else None
                t = {"r2": r2, "base_url": None, "boundary": item.get("boundary", "prepared")}
                bq = item.get("base_url")
                if bq:
                    if f"{iid}#base" in failed:
                        t["base_url"] = {"error": "does not compile: " + failed[f"{iid}#base"]}
                    else:
                        rb = [r for r in by_id.get(iid, []) if r["part"] == "base"]
                        orig = next((r for r in rb if r["cand"] == "" and "url" in r), None)
                        if orig is None:
                            t["base_url"] = {"error": "no dump"}
                        else:
                            m = re.match(r"^\w+://[^/]+(/.*)$", orig["url"])
                            expected = bq["staging"] + (m.group(1) if m else "/")
                            urls = {r["cand"]: r.get("url", "error: " + r.get("error", "?")) for r in rb if r["cand"]}
                            keeps = [c for c in bq["candidates"] if urls.get(c) == expected]
                            t["base_url"] = {"keep": bq["keep"], "expected_url": mask(expected, canaries),
                                             "results": {c: mask(u, canaries) for c, u in urls.items()},
                                             "keeps": keeps}
                scorable_r2 = r2.get("resolvable") and r2.get("verified")
                scorable_b = bool(t["base_url"] and t["base_url"].get("keeps"))
                if not scorable_r2 and not scorable_b:
                    reason = r2.get("reason") or "not resolvable"
                    t = None if not bq else t
                if not scorable_r2:
                    totals["r2_unscorable"] += 1
                    drops.append({"id": iid, "part": "send_returns/error_type",
                                  "reason": r2.get("reason") or "not resolvable"})
                if bq and not scorable_b:
                    drops.append({"id": iid, "part": "base_url", "reason": json.dumps(t["base_url"] if t else None)})
            elif item["kind"] == "call":
                r2c = r2s[iid.replace("/c", "/r")]
                ref = reference_call(b, pick)
                if f"{iid}#ref" in failed:
                    reason = "reference call does not compile: " + failed[f"{iid}#ref"]
                else:
                    passes, tries = exchanges(by_id, iid, "r3")
                    p0, p1 = passes.get(0), passes.get(1)
                    reqs = p0["requests"] if p0 else []
                    rec_a = [req_record(r, canaries) for r in reqs]
                    rec_b = [req_record(r, canaries) for r in (p1["requests"] if p1 else [])]
                    fx = next((f for f in fixtures_of[b["short"]] if p0 and f["name"] == p0["fixture"]), None)
                    vol = volatility(rec_a, rec_b) if p1 else None
                    # the result is checked when the binding checks a `Result` (`is_ok`) and both
                    # passes succeeded with the chosen reply (it decodes into the declared output;
                    # for a stream, the stream opened)
                    binding = call_binding(r2c)
                    checked = bool(binding["result"] == "is_ok" and p0 and p1
                                   and p0["outcome"] is None and p1["outcome"] is None)
                    t = {"reference": ref, "reference_compiles": True, "client": pick["client"],
                         "binding": binding, "boundary": item.get("boundary", "prepared"),
                         "base_path": base_path_of(next(c for c, _ in sdk.clients if c["name"] == pick["client"])["stmts"]["base"]),
                         "recorded": rec_a, "recorded_again": rec_b, "volatile": vol,
                         "fixture": fx, "fixture_tries_failed": len(tries),
                         "reference_outcome": p0["outcome"] if p0 else "the recorder printed nothing",
                         "result_checked": checked,
                         "check_available": bool(reqs) and not (vol or {}).get("sequence_differs")}
                    if not checked:
                        t["result_unchecked_reason"] = (
                            t["binding"]["reason"] if t["binding"]["result"] != "is_ok"
                            else f"no reply among {len(tries)} fixtures decodes into the declared output: "
                                 + (tries[0][1] if tries else (p0 or {}).get("outcome") or "?")[:300])
                        drops.append({"id": iid, "part": "call (result check)", "reason": t["result_unchecked_reason"]})
                    if not reqs:
                        t["check_unavailable_reason"] = ("the reference call reached no local receiver" + (f" ({p0['outcome']})" if p0 and p0["outcome"] else "")
                                                         if f"{iid}#refrun" not in failed else "recorder does not compile: " + failed[f"{iid}#refrun"])
                        drops.append({"id": iid, "part": "call (request check)", "reason": t["check_unavailable_reason"]})
                    elif (vol or {}).get("sequence_differs"):
                        t["check_unavailable_reason"] = "the reference's requests differ between two runs"
                        drops.append({"id": iid, "part": "call (request check)", "reason": t["check_unavailable_reason"]})
            if t is not None and reason is None:
                out["items"][iid] = dict(t, kind=item["kind"])
                totals[f"{item['kind']}_ok"] += 1
            else:
                out["drops"].append({"id": iid, "reason": reason})
                if item["kind"] != "result":
                    drops.append({"id": iid, "part": item["kind"], "reason": reason})
                totals[f"{item['kind']}_dropped"] += 1
        C.write_json(os.path.join(bank_dir, "truth", f"{b['short']}.json"), out)
    if not a.sdk:
        C.write_json(os.path.join(bank_dir, "truth", "drops.json"),
                     {"compile_log": log, "totals": dict(totals), "drops": drops})
    else:
        print(json.dumps({"compile_log": log}, indent=1))
    print(json.dumps(dict(sorted(totals.items())), indent=1))
    for d in drops:
        print("DROP", d["id"], d["part"], (d["reason"] or "")[:200])


def git_head(repo):
    try:
        return subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


