WIRE_KEYS = "Answer each question with `method`, `url`, `headers`, `body`, `content_type`, `accept`."
WIRE_HEADER_BOUNDARY = (
    "For `headers`, `accept` and `content_type`, include only headers the SDK and Concord set at "
    "the stated observation boundary, excluding headers the HTTP client adds on its own. "
    "Use `null` for `accept` or `content_type` when the SDK and Concord set no corresponding "
    "header at that boundary, even if the HTTP client later adds a default."
)


def stated_wire_question(it):
    """Replace only the stored wire preamble; keep the bank's call snippet. No truth lookup."""
    asks = {
        "operation": "What request does `call.send().await` send, including send-policy edits?",
        "prepared": "What request does `call.prepare()` build, before any send-policy edits?",
    }
    boundary = it.get("boundary")
    if boundary not in asks:
        raise SystemExit(f"{it['id']}: --stated-boundary needs an operation or prepared boundary")
    _, fence, snippet = it["question"].partition("\n\n```rust\n")
    if not fence:
        raise SystemExit(f"{it['id']}: --stated-boundary needs a stored wire call snippet")
    question = (asks[boundary] + " Give `method`, `url`, `headers` (secret values as `<secret>`), "
                "`body`, `content_type` and `accept`. " + WIRE_HEADER_BOUNDARY + fence + snippet)
    # Match fill's whitespace normalization so the metadata hashes the exact packed question.
    return re.sub(r"\n{3,}", "\n\n", question).strip()


def fill(template, cheatsheet, decl_types, docs, questions, with_docs):
    body = template.split("\n---\n", 1)[1].lstrip("\n") if "\n---\n" in template else template
    body = body.replace("{for R2/R3 banks: the SDK's generated documentation, as text}",
                        "the SDK's generated documentation, as text" if with_docs
                        else "(no generated documentation in this bank)")
    body = body.replace("{CHEATSHEET}", "## 1. Cheat sheet\n\n" + cheatsheet.strip())
    body = body.replace("{DECLARATION_AND_TYPES}", decl_types)
    body = body.replace("{GENERATED_DOCS_IF_ANY}", ("## 3. Generated documentation\n\n```text\n" + docs.strip() + "\n```") if with_docs else "")
    body = body.replace("{QUESTIONS}", "## 4. Questions\n\n" + questions.strip())
    return re.sub(r"\n{3,}", "\n\n", body).strip() + "\n"


def questions_text(bank, session, stated_boundary=False):
    items = [it for it in bank["items"] if it["session"] == session]
    parts = []
    if session == "rc":
        ctors = []
        for name in sorted({bank["picks"][it["pick"]]["client"] for it in items}):
            ctors.append(f"let api = {bank['clients'][name]['ctor']};")
        parts.append("In these questions `api` is the client built like this:\n\n```rust\n" + "\n".join(ctors) + "\n```")
        keys = ("Answer a result question with `send_returns`, `error_type` (and `base_url` when asked), "
                "each type written out in full: no `_`, `impl`, `Self`, elided lifetimes or "
                "`<T as Trait>::Name` projections; "
                "a call question with `code`, one expression ending in `.send().await`.")
    else:
        keys = WIRE_KEYS
        if stated_boundary:
            keys += " Use the observation boundary stated in each question. " + WIRE_HEADER_BOUNDARY
    parts.append(keys + " Every answer object carries its `q` number and a `confidence`.")
    for it in items:
        parts.append(f"### Q{it['q']}\n\n{question_of(bank, it, stated_boundary)}")
    return "\n\n".join(parts)


def question_of(bank, it, stated_boundary=False):
    """An item's question text. Opt-in wire wording states the truth's header boundary.
    Call questions are worded here with the current R3 answer
    contract (`generate.call_question_text`) from the stored `intent`, so banks generated before
    the contract changed (generator v1) show the contract the scorer applies."""
    if it["kind"] == "wire" and stated_boundary:
        return stated_wire_question(it)
    if it["kind"] != "call":
        return it["question"]
    intent = it.get("intent")
    if not intent:
        m = re.search(r"sends it with `\.send\(\)\.await`: (.*)\. Your code runs before", it["question"], re.S)
        if not m:
            raise SystemExit(f"{it['id']}: call question without a recoverable intent")
        intent = m.group(1)
    return G.call_question_text(bank["picks"][it["pick"]]["client"], intent)


def leak_scan(bank, session, materials, truth, navs, cheatsheet=""):
    """Answer-bearing text in the materials (cheat sheet and questions excluded): the full truth URL
    of a wire item; for a call item, a Rust call chain that spells its navigation (the full path
    of two or more segments, or the endpoint followed by `.send()`, `.prepare()` or one of its
    setters, so root endpoints and chains with arguments count, see `common.chain_hits`); any
    endpoint call chain at all (`endpoint_chains`); and the exact R2 truth type (expected for
    docs-assisted sessions: rustdoc states each generated `send()` signature). The cheat sheet's
    generic example is scanned separately (`cheatsheet_chain`, informational)."""
    flat = re.sub(r"\s+", "", materials)
    found = C.scan_chains(materials, navs)
    hits = {"wire_url": [], "call_chain": [], "call_chain_text": {}, "endpoint_chains": sorted({c for c, _ in found}),
            "cheatsheet_chain": [], "result_type_in_docs": [], "truth_missing": truth is None}
    sheet = C.scan_chains(cheatsheet, navs) if cheatsheet else []
    for it in bank["items"]:
        if it["session"] != session:
            continue
        pick = bank["picks"][it["pick"]]
        t = (truth or {}).get(it["id"])
        if it["kind"] == "wire" and t and t.get("url") and re.search(re.escape(t["url"]) + r"(?![\w/.-])", materials):
            hits["wire_url"].append(it["id"])
        if it["kind"] == "call":
            path = tuple(pick["scopes"]) + (pick["endpoint"],)
            texts = sorted({c for c, paths in found if path in paths})
            if texts:
                hits["call_chain"].append(it["id"])
                hits["call_chain_text"][it["id"]] = texts
            if any(path in paths for _, paths in sheet):
                hits["cheatsheet_chain"].append(it["id"])
        if it["kind"] == "result" and t and t.get("r2", {}).get("send_returns"):
            if re.sub(r"\s+", "", t["r2"]["send_returns"]) in flat:
                hits["result_type_in_docs"].append(it["id"])
    return hits


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--bank", required=True)
    ap.add_argument("--sdk", nargs="*")
    ap.add_argument("--prompt", default=C.DEFAULT_PROMPT)
    ap.add_argument("--repo", default=C.REPO)
    ap.add_argument("--no-rustdoc-build", action="store_true")
    ap.add_argument("--wire-docs", action="store_true",
                    help="also give wire (R1) sessions the generated rustdoc (default: R2/R3 sessions only, "
                         "as prompts/probe_reader.md and DESIRABILITY.md R1 describe)")
    ap.add_argument("--generated-docs", action="store_true",
                    help="append raw endpoint request-type/navigation docs to every session; "
                         "build the arm commit in a provenance-checked isolated target")
    ap.add_argument("--docs-commit", help="arm commit for --generated-docs (default: --repo HEAD; exact git archive)")
    ap.add_argument("--stated-boundary", action="store_true",
                    help="state one SDK/Concord header boundary for headers, accept and content_type "
                         "in wire questions (exclude HTTP-client defaults)")
    a = ap.parse_args()
    if a.docs_commit and not a.generated_docs:
        ap.error("--docs-commit requires --generated-docs")
    bank_dir = os.path.abspath(a.bank)
    template = open(a.prompt, encoding="utf-8").read()
    cheat = open(os.path.join(a.repo, "docs", "CHEATSHEET.md"), encoding="utf-8").read()
    banks = []
    for f in sorted(os.listdir(bank_dir)):
        if f.endswith(".json") and f != "index.json":
            b = C.read_json(os.path.join(bank_dir, f))
            if not a.sdk or b["short"] in a.sdk:
                banks.append(b)
    log = {}
    if a.generated_docs:
        if not banks:
            ap.error("--generated-docs: no selected SDK banks")
        import generated_docs as GD
        a.repo, generated_rd_dir, log = GD.prepare(a.repo, a.docs_commit, banks, a.no_rustdoc_build)
        cheat = open(os.path.join(a.repo, "docs", "CHEATSHEET.md"), encoding="utf-8").read()
    elif not a.no_rustdoc_build:
        build_rustdoc([b["pkg"] for b in banks], log)
    out_dir = os.path.join(bank_dir, "packed")
    os.makedirs(out_dir, exist_ok=True)
    for b in banks:
        sdk = C.Sdk(os.path.join(a.repo, "examples", b["sdk"]), a.repo)
        navs = C.endpoint_navs(sdk)
        items = named_items(sdk, declaration_blocks(sdk), b)
        rd_path = os.path.join(generated_rd_dir if a.generated_docs else os.path.join(C.CARGO_TARGET_DIR, "doc"),
                               f"{b['crate']}.json")
        dj = C.read_json(rd_path) if os.path.isfile(rd_path) else None
        named = {it["name"].split("::")[0] for it in items if it["kind"] in ("struct", "enum", "type", "trait")}

        def materials_for(nv):
            blocks = declaration_blocks(sdk, nv)
            types_text, cut = render_items(sdk, items, nv)
            decl = "## 2. Declaration\n\n" + "\n\n".join(f"```rust\n// {rel}\n{src}\n```" for rel, src in blocks)
            decl += "\n\nThe Rust items it names (from the SDK source):\n\n```rust\n" + types_text.strip() + "\n```"
            return decl, (render_rustdoc(dj, sdk, named, nv) if dj is not None else ""), cut

        decl, docs, cut = materials_for(navs)
        decl_unf, docs_unf, _ = materials_for(None)
        rd_meta = {}
        if dj is not None:
            rd_meta = {"source": "rustdoc JSON (nightly, --document-private-items), rendered to text by pack.py",
                       "format_version": dj.get("format_version"), "toolchain": log.get("rustdoc_toolchain"),
                       "json_sha256": C.sha256_file(rd_path)}
        else:
            rd_meta = {"source": "missing", "path": rd_path}
        meta = {"sdk": b["short"], "prompt_sha256": hashlib.sha256(template.encode()).hexdigest(),
                "cheatsheet_sha256": hashlib.sha256(cheat.encode()).hexdigest(), "rustdoc": rd_meta,
                "stated_boundary": a.stated_boundary,
                "named_items": [it["name"] for it in items], "named_items_cut": cut, "sessions": {}}
        truth_path = os.path.join(bank_dir, "truth", f"{b['short']}.json")
        truth = C.read_json(truth_path)["items"] if os.path.isfile(truth_path) else None
        for session, with_docs in (("wire", a.wire_docs), ("rc", True)):
            questions = questions_text(b, session, a.stated_boundary)
            text = fill(template, cheat, decl, docs, questions, with_docs)
            if a.generated_docs:
                text = text.replace("(no generated documentation in this bank)",
                                    "the endpoint documentation appended in section 5")
            materials = text.split("## 4. Questions", 1)[0].split("## 2. Declaration", 1)[-1]
            meta.setdefault("leak_scan", {})[session] = leak_scan(b, session, materials, truth, navs, cheat)
            # the same scan without the call-chain filter: what the filter removed (validation)
            unf = fill(template, cheat, decl_unf, docs_unf, questions, with_docs)
            unf = unf.split("## 4. Questions", 1)[0].split("## 2. Declaration", 1)[-1]
            ls = leak_scan(b, session, unf, truth, navs)
            meta.setdefault("leak_scan_unfiltered", {})[session] = {k: ls[k] for k in ("call_chain", "call_chain_text", "endpoint_chains")}
            if a.generated_docs:
                suffix, exposure = GD.appendix(dj, sdk, b, session)
                exposure.update(commit=log["commit"], provenance=log["provenance"],
                                rustdoc_json_sha256=C.sha256_file(rd_path),
                                base_prompt_sha256=GD.sha256(text))
                text += suffix
                exposure["prompt_sha256"] = GD.sha256(text)
                meta.setdefault("generated_docs_exposure", {})[session] = exposure
            path = os.path.join(out_dir, f"{b['short']}.{session}.md")
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            meta["sessions"][session] = {"file": os.path.basename(path), "chars": len(text),
                                         "sha256": hashlib.sha256(text.encode()).hexdigest(),
                                         "questions": {str(it["q"]): it["id"] for it in b["items"] if it["session"] == session}}
            if a.stated_boundary and session == "wire":
                meta["sessions"][session]["questions_text_sha256"] = hashlib.sha256(questions.encode()).hexdigest()
                meta["sessions"][session]["question_text_sha256"] = {
                    str(it["q"]): hashlib.sha256(question_of(b, it, True).encode()).hexdigest()
                    for it in b["items"] if it["session"] == session
                }
        C.write_json(os.path.join(out_dir, f"{b['short']}.meta.json"), meta)
        print(f"{b['short']}: wire {meta['sessions']['wire']['chars']} chars, rc {meta['sessions']['rc']['chars']} chars, "
              f"named items {len(items)} (cut {cut}), rustdoc {rd_meta.get('source', '?')[:12]}")
    if log:
        C.write_json(os.path.join(out_dir, "pack_log.json"), log)


if __name__ == "__main__":
    main()
