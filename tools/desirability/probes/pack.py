FN_LINES = 60              # longest free function body included


# ---------------------------------------------------------------- declaration and named items

def no_examples(text, navs, markdown=False):
    """Fenced examples, then call chains on the SDK's generated client/scopes/endpoints, removed
    (`navs` None: fenced examples only, the unfiltered variant the leak scan validates against)."""
    text = C.strip_md_examples(text) if markdown else C.strip_doc_examples(text)
    return C.strip_call_examples(text, navs, markdown) if navs is not None else text


def declaration_blocks(sdk, navs=None):
    """[(relative file, source of `concord::api! { .. }`)] in file order."""
    out = []
    for p, text in sdk.files.items():
        clean = C.strip_strings_and_comments(text)
        for s, e in api_spans(text, clean):
            start = text.rfind("\n", 0, s) + 1
            # include doc/attribute lines directly above the macro call
            start = C.attr_start(text, start)
            out.append((sdk.rel(p), no_examples(text[start:e + 1], navs)))
    return out


def generated_names(sdk):
    names = set()
    for c, _ in sdk.clients:
        names.add(c["name"])
        names.add(c["name"] + "Config")
        names.update(c["stmts"].get("groups", {}).keys())
    return names


def named_items(sdk, blocks, bank):
    """SDK items the declaration names (types, consts, statics, free functions), plus the
    transitive field types and `impl Default` of the body types the snippets build with
    `T::default()`, and the methods called in initializers (`Type::method()`)."""
    gen = generated_names(sdk)
    order, seen = [], set()

    def add(name, kinds=("struct", "enum", "type", "trait", "const", "static", "union", "fn")):
        if name in seen or name in gen:
            return None
        it = sdk.find(name, kinds)
        if it is None or (it["kind"] == "fn" and it["indent"] != 0):
            return None
        seen.add(name)
        order.append(it)
        return it

    code = "\n".join(C.strip_strings_and_comments(t) for _, t in blocks)
    for m in re.finditer(r"\b([A-Za-z_][A-Za-z0-9_]*)\b", code):
        w = m.group(1)
        if w[0].isupper():
            add(w)
        elif re.match(r"\s*\(", code[m.end():]) and code[max(0, m.start() - 1)] != ".":
            add(w, ("fn",))
    # methods called in initializers / header templates: `Type::method(`
    for m in re.finditer(r"\b([A-Z]\w*)::([a-z_]\w*)\s*\(", code):
        ty, meth = m.group(1), m.group(2)
        for im in sdk.impls:
            if re.match(r"impl\s*(<.*?>)?\s*" + re.escape(ty) + r"\b", im["header"]) and " for " not in im["header"]:
                fm = re.search(r"(?m)^([ \t]*)(?:pub(?:\([^)]*\))?\s+)?(?:const\s+)?fn\s+" + re.escape(meth) + r"\b", im["text"])
                if fm:
                    sub = im["text"][fm.start():]
                    end = C.item_end(C.strip_strings_and_comments(sub), sub.index("fn"), "fn")
                    key = f"{ty}::{meth}"
                    if end and key not in seen:
                        seen.add(key)
                        order.append({"kind": "method", "name": key, "file": im["file"],
                                      "text": f"impl {ty} {{\n" + sub[:end].rstrip() + "\n    // ..\n}"})
    # body types built with `T::default()`
    body_types = set()
    for p in bank["picks"]:
        for v in p["values"]:
            if (v.get("kind") or "").startswith("default:") and v["state"] in ("required", "set"):
                t = C.parse_type(v["kind"].split(":", 1)[1])
                body_types.add(t[1][-1] if t[0] == "path" else None)
    frontier = [b for b in body_types if b]
    depth = 0
    while frontier and depth < 4:
        nxt = []
        for name in frontier:
            it = sdk.find(name, ("struct", "enum", "type")) if name not in seen else None
            if it is not None:
                seen.add(name)
                order.append(it)
            it = it or sdk.find(name, ("struct", "enum", "type"))
            if it is None:
                continue
            for im in sdk.impls:
                if re.match(r"impl\s*(<.*?>)?\s*(?:[\w:]*::)?Default\s+for\s+" + re.escape(name) + r"\b", im["header"]):
                    key = f"impl Default for {name}"
                    if key not in seen:
                        seen.add(key)
                        order.append({"kind": "impl", "name": key, "file": im["file"], "text": im["text"]})
            for w in re.findall(r"\b([A-Z][A-Za-z0-9_]*)\b", C.strip_strings_and_comments(it["text"])):
                if w not in seen and sdk.find(w, ("struct", "enum", "type")):
                    nxt.append(w)
        frontier = nxt
        depth += 1
    return order


def render_items(sdk, items, navs=None):
    parts, total, cut = [], 0, 0
    for it in items:
        text = it["text"]
        if it["kind"] == "fn":
            lines = text.split("\n")
            if len(lines) > FN_LINES:
                text = "\n".join(lines[:FN_LINES]) + "\n    // .. (truncated)\n}"
        piece = f"// {sdk.rel(it['file'])}\n{no_examples(text, navs)}\n"
        if total + len(piece) > TYPES_BUDGET:
            cut += 1
            continue
        parts.append(piece)
        total += len(piece)
    return "\n".join(parts), cut


# ---------------------------------------------------------------- rustdoc JSON → text

def clean_path(p):
    p = re.sub(r"^(\$crate|::concord|concord)::__macro::concord_core::", "concord::", p)
    p = re.sub(r"^\$crate::", "", p)
    p = re.sub(r"^:?:?concord_core::", "concord::", p)
    m = re.match(r"^:?:?(core|std|alloc)::(?:\w+::)*(\w+)$", p)
    if m:
        return m.group(2)
    return p.lstrip(":")


def r_args(a):
    if not a:
        return ""
    if "angle_bracketed" in a:
        ab = a["angle_bracketed"]
        items = []
        for x in ab.get("args", []):
            if isinstance(x, dict) and "type" in x:
                items.append(r_type(x["type"]))
            elif isinstance(x, dict) and "lifetime" in x:
                items.append(x["lifetime"])
            elif isinstance(x, dict) and "const" in x:
                c = x["const"]
                items.append(c.get("expr") or c.get("value") or "_")
            else:
                items.append("_")
        for c in ab.get("constraints", []):
            b = c.get("binding", {})
            if "equality" in b:
                eq = b["equality"]
                items.append(f"{c['name']} = " + (r_type(eq["type"]) if "type" in eq else str(eq.get("constant", "?"))))
            elif "constraint" in b:
                items.append(f"{c['name']}: " + " + ".join(r_bound(x) for x in b["constraint"]))
        return "<" + ", ".join(items) + ">" if items else ""
    if "parenthesized" in a:
        pz = a["parenthesized"]
        out = "(" + ", ".join(r_type(t) for t in pz.get("inputs", [])) + ")"
        if pz.get("output"):
            out += " -> " + r_type(pz["output"])
        return out
    return ""


def r_bound(b):
    if "trait_bound" in b:
        tb = b["trait_bound"]
        mod = "?" if tb.get("modifier") == "maybe" else ""
        return mod + clean_path(tb["trait"]["path"]) + r_args(tb["trait"].get("args"))
    if "outlives" in b:
        return b["outlives"]
    if "use" in b:
        return "use<..>"
    return "?"


def r_type(t):
    if t is None:
        return "()"
    if isinstance(t, str):
        return t
    k, v = next(iter(t.items()))
    if k == "resolved_path":
        return clean_path(v["path"]) + r_args(v.get("args"))
    if k in ("generic", "primitive"):
        return v
    if k == "tuple":
        return "(" + ", ".join(r_type(x) for x in v) + ("," if len(v) == 1 else "") + ")"
    if k == "slice":
        return "[" + r_type(v) + "]"
    if k == "array":
        return f"[{r_type(v['type'])}; {v['len']}]"
    if k == "borrowed_ref":
        lt = (v.get("lifetime") + " ") if v.get("lifetime") else ""
        return "&" + lt + ("mut " if v.get("is_mutable") else "") + r_type(v["type"])
    if k == "raw_pointer":
        return ("*mut " if v.get("is_mutable") else "*const ") + r_type(v["type"])
    if k == "impl_trait":
        return "impl " + " + ".join(r_bound(b) for b in v)
    if k == "dyn_trait":
        s = "dyn " + " + ".join(clean_path(p["trait"]["path"]) + r_args(p["trait"].get("args")) for p in v["traits"])
        return s + (" + " + v["lifetime"] if v.get("lifetime") else "")
    if k == "qualified_path":
        tr = v.get("trait")
        if tr:
            return f"<{r_type(v['self_type'])} as {clean_path(tr['path'])}{r_args(tr.get('args'))}>::{v['name']}"
        return f"{r_type(v['self_type'])}::{v['name']}"
    if k == "function_pointer":
        sig = v.get("sig", {})
        out = sig.get("output")
        return "fn(" + ", ".join(r_type(x[1]) for x in sig.get("inputs", [])) + ")" + (" -> " + r_type(out) if out else "")
    if k == "infer":
        return "_"
    return str(v)


def r_gparams(gens, skip_synthetic=True):
    out = []
    for p in gens.get("params", []):
        kind = p.get("kind", {})
        if "type" in kind:
            if kind["type"].get("is_synthetic") and skip_synthetic:
                continue
            b = kind["type"].get("bounds") or []
            out.append(p["name"] + (": " + " + ".join(r_bound(x) for x in b) if b else ""))
        elif "lifetime" in kind:
            out.append(p["name"])
        elif "const" in kind:
            out.append(f"const {p['name']}: {r_type(kind['const'].get('type'))}")
    return "<" + ", ".join(out) + ">" if out else ""


def r_where(gens):
    preds = []
    for w in gens.get("where_predicates", []):
        if "bound_predicate" in w:
            bp = w["bound_predicate"]
            preds.append(r_type(bp["type"]) + ": " + " + ".join(r_bound(b) for b in bp.get("bounds", [])))
    return (" where " + ", ".join(preds)) if preds else ""


def r_fn(item):
    f = item["inner"]["function"]
    params = []
    for name, t in f["sig"]["inputs"]:
        if name == "self":
            if t == {"generic": "Self"}:
                params.append("self")
            elif "borrowed_ref" in t and t["borrowed_ref"]["type"] == {"generic": "Self"}:
                params.append("&mut self" if t["borrowed_ref"].get("is_mutable") else "&self")
            else:
                params.append("self: " + r_type(t))
        else:
            params.append(f"{name}: {r_type(t)}")
    out = f["sig"].get("output")
    hdr = f.get("header", {})
    pre = ("const " if hdr.get("is_const") else "") + ("async " if hdr.get("is_async") else "")
    return (f"{pre}fn {item['name']}{r_gparams(f.get('generics', {}))}({', '.join(params)})"
            + (f" -> {r_type(out)}" if out is not None else "") + r_where(f.get("generics", {})))


def vis(item):
    v = item.get("visibility")
    if v == "public":
        return "pub "
    if v == "crate":
        return "pub(crate) "
    if isinstance(v, dict):
        return "pub(in ..) "
    return ""


def hidden(item):
    return "hidden" in json.dumps(item.get("attrs", [])) or (item.get("name") or "").startswith("__")


def indent(text, n):
    pad = " " * n
    return "\n".join(pad + ln if ln.strip() else "" for ln in text.split("\n"))


def r_impl_header(imp):
    im = imp["inner"]["impl"]
    tr = im.get("trait")
    g = r_gparams(im.get("generics", {}))
    head = f"impl{g} "
    if tr:
        head += ("!" if im.get("is_negative") else "") + clean_path(tr["path"]) + r_args(tr.get("args")) + " for "
    return head + r_type(im["for"]) + r_where(im.get("generics", {}))


def render_rustdoc(doc_json, sdk, named, navs=None):
    """Text of the generated items (spans inside `api!` blocks) and the trait impls of `named`."""
    import rustdoc_metrics  # tools/desirability: block_line_ranges / inside
    idx = doc_json["index"]
    ranges = rustdoc_metrics.block_line_ranges(os.path.join(sdk.dir, "src"))

    def generated(it):
        return rustdoc_metrics.inside(it.get("span"), ranges, sdk.dir)

    out = []
    tops = [it for it in idx.values() if it.get("crate_id") == 0 and generated(it)
            and any(k in it["inner"] for k in ("struct", "enum", "trait", "type_alias"))]
    tops.sort(key=lambda it: (0 if "struct" in it["inner"] else 1, it.get("name") or ""))
    for it in tops:
        if hidden(it):
            continue
        kind = next(k for k in ("struct", "enum", "trait", "type_alias") if k in it["inner"])
        inner = it["inner"][kind]
        title = {"struct": "struct", "enum": "enum", "trait": "trait", "type_alias": "type"}[kind]
        lines = [f"{vis(it)}{title} {it['name']}{r_gparams(inner.get('generics', {}))}"]
        if it.get("docs"):
            lines.append(indent(it["docs"].strip(), 4))
        if kind == "struct":
            fields = (inner.get("kind", {}).get("plain") or {}).get("fields", [])
            pubf = [idx[str(f)] for f in fields if str(f) in idx and idx[str(f)].get("visibility") == "public"]
            if pubf:
                lines.append("    fields:")
                for f in pubf:
                    lines.append(f"        pub {f['name']}: {r_type(f['inner']['struct_field'])}")
                    if f.get("docs"):
                        lines.append(indent(f["docs"].strip(), 12))
        if kind == "trait":
            for mid in inner.get("items", []):
                m = idx.get(str(mid))
                if m and "function" in m["inner"] and not hidden(m):
                    lines.append("    " + r_fn(m) + ";")
                    if m.get("docs"):
                        lines.append(indent(m["docs"].strip(), 8))
        impls = inner.get("impls", []) if kind != "trait" else []
        derived = []
        for iid in impls:
            imp = idx.get(str(iid))
            if not imp:
                continue
            im = imp["inner"]["impl"]
            if im.get("is_synthetic") or im.get("blanket_impl") is not None:
                continue
            if im.get("trait") is not None and not generated(imp):
                derived.append(clean_path(im["trait"]["path"]) + r_args(im["trait"].get("args")))
                continue
            lines.append("    " + r_impl_header(imp) + " {")
            for mid in im.get("items", []):
                m = idx.get(str(mid))
                if not m or hidden(m):
                    continue
                if "function" in m["inner"]:
                    lines.append("        " + vis(m) + r_fn(m) + ";")
                    if m.get("docs"):
                        lines.append(indent(m["docs"].strip(), 12))
                elif "assoc_type" in m["inner"]:
                    at = m["inner"]["assoc_type"]
                    lines.append(f"        type {m['name']} = {r_type(at.get('type'))};")
                elif "assoc_const" in m["inner"]:
                    ac = m["inner"]["assoc_const"]
                    lines.append(f"        const {m['name']}: {r_type(ac.get('type'))};")
            lines.append("    }")
        if derived:
            lines.append("    also implements: " + ", ".join(sorted(set(derived))))
        out.append("\n".join(lines))
    # trait impls of the SDK types the declaration names
    named_out = []
    for it in idx.values():
        if it.get("crate_id") != 0 or it.get("name") not in named or generated(it):
            continue
        kind = next((k for k in ("struct", "enum") if k in it["inner"]), None)
        if not kind:
            continue
        rows = []
        for iid in it["inner"][kind].get("impls", []):
            imp = idx.get(str(iid))
            if not imp:
                continue
            im = imp["inner"]["impl"]
            if im.get("is_synthetic") or im.get("blanket_impl") is not None or im.get("trait") is None:
                continue
            assoc = []
            for mid in im.get("items", []):
                m = idx.get(str(mid))
                if m and "assoc_type" in m["inner"]:
                    assoc.append(f"type {m['name']} = {r_type(m['inner']['assoc_type'].get('type'))};")
            rows.append(r_impl_header(imp) + (" { " + " ".join(assoc) + " }" if assoc else ""))
        if rows:
            named_out.append(f"{it['name']}:\n" + "\n".join("    " + r for r in sorted(set(rows))))
    text = no_examples("\n\n".join(out), navs, markdown=True)
    if named_out:
        text += "\n\n# Trait implementations of the SDK types named in the declaration\n\n" + "\n\n".join(sorted(named_out))
    return text


def build_rustdoc(pkgs, log):
    env = C.cargo_env()
    env["RUSTDOCFLAGS"] = "-Z unstable-options --output-format json --document-private-items"
    args = ["cargo", "+nightly", "doc", "--no-deps", "--lib"]
    for p in pkgs:
        args += ["-p", p]
    r = subprocess.run(args, cwd=C.REPO, env=env, capture_output=True, text=True)
    log["rustdoc_build_exit"] = r.returncode
    if r.returncode:
        log["rustdoc_build_stderr"] = r.stderr[-3000:]
    v = subprocess.run(["rustc", "+nightly", "--version"], capture_output=True, text=True)
    log["rustdoc_toolchain"] = v.stdout.strip()


