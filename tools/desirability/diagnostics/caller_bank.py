"""I5 caller-side bank: seeded caller mistakes compiled against five SDKs (metric R5, diagnostic).

    python3 -I tools/desirability/diagnostics/caller_bank.py --scratch WT [--sdk SDK ..]
    python3 -I tools/desirability/diagnostics/score.py bank tools/desirability/diagnostics/bank

`WT` is a throwaway `git worktree add --detach` checkout (never the committed tree). For each
SDK this script writes one test file per case into `WT/examples/<sdk>-sdk/tests/`, compiles it
alone (`cargo test -p <pkg> --test <case> --no-run`, one cargo command at a time), and saves
under `bank/`:

- `<sdk>.<case>.rs`     the caller's file (the line marked `// SEEDED` is the mistake);
- `<sdk>.<case>.stderr` the compiler output;
- `<sdk>.<case>.json`   `{"user_file", "expected", "generated_names", ...}` for `score.py bank`.

Instrument controls (PLAN_AMENDMENT_A1 §6): per SDK, a known-good file (`<sdk>.control.rs`)
holding the corrected line of every case must compile; a case whose first error does not concern
its seeded line (the line is cited by neither the primary nor a secondary span of the first error
block) is dropped and recorded in `bank/DROPPED.json`; a case that compiles is kept with an empty
`.stderr` and counts as a failure (the mistake went undiagnosed).

Case kinds (DESIRABILITY § I5): `default_body` (a body passed as `Default::default()` where the
generated argument type cannot be inferred), `into_body` (the same with `.into()`),
`wrong_setter` (a setter given a value of the wrong type), `missing_scope_value` (a positional
scope value left out), `send_mismatch` (`let x: WrongType = ...send().await?`), `wrong_format`
(a format type that cannot decode the document: `document::<Text, T>`). Where an SDK has no body
or no scope value, the nearest positional value is used and the case says so (`variant`).

`generated_names`: the generated types of the SDK's declarations (client config, scope and
endpoint handles, parameter-group traits), from `tools/desirability/decl.py`, minus the names the
caller's file itself writes. Run Python with `-I`.
"""
