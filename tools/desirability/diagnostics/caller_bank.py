def camel(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("_") if p)


def generated_names(sdk_root, files):
    """Generated type names of the declarations in `files` (config, scopes, endpoints, groups)."""
    names = set()
    for rel in files:
        for client in decl.parse_file(open(os.path.join(sdk_root, rel), encoding="utf-8").read()):
            base = client["name"]
            names.add(base + "Config")
            names.update(client.get("stmts", {}).get("groups", {}).keys())

            def visit(owner, prefix):
                for child in owner.get("children", []):
                    name = prefix + camel(child["name"])
                    names.add(name)
                    if child["kind"] != "endpoint":
                        visit(child, name)
            visit(client, base)
    return sorted(names)


def render(sdk, spec, case, line):
    body = (f"//! I5 caller-bank case `{case}` ({sdk}). {DOC}\n"
            "#![allow(unused, dead_code, clippy::all)]\n\n"
            f"{spec['prelude']}\n\n"
            "async fn caller() -> Result<(), Box<dyn std::error::Error>> {\n"
            f"    {spec['setup']}\n")
    seeded = None
    for ln in ([line] if isinstance(line, str) else line):
        body += f"    {ln} // SEEDED\n" if seeded is None and isinstance(line, str) else f"    {ln}\n"
        if seeded is None and isinstance(line, str):
            seeded = body.count("\n")
    body += "    Ok(())\n}\n"
    return body, seeded


def compile_case(wt, pkg, sdk_dir, test_name, text):
    path = os.path.join(wt, sdk_dir, "tests", f"{test_name}.rs")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    env = dict(os.environ, CARGO_TERM_COLOR="never")
    r = subprocess.run(["cargo", "test", "-p", pkg, "--test", test_name, "--no-run"], cwd=wt,
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, env=env)
    os.remove(path)
    return r.returncode, r.stderr


def first_block(stderr):
    lines = stderr.splitlines()
    for i, ln in enumerate(lines):
        if ln.startswith("error"):
            block = [ln]
            for nxt in lines[i + 1:]:
                if nxt.startswith(("error", "warning")):
                    break
                block.append(nxt)
            return block
    return []


def concerns_line(block, user_file, line):
    """Whether the first error block cites `line` of `user_file` (primary or secondary span)."""
    current = None
    for ln in block:
        m = SPAN.search(ln)
        if m:
            current = m.group(1)
            if os.path.normpath(current).endswith(os.path.normpath(user_file)) and int(m.group(2)) == line:
                return True
            continue
        m = SECONDARY.match(ln)
        if m and current and os.path.normpath(current).endswith(os.path.normpath(user_file)) \
                and int(m.group(1)) == line:
            return True
    return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scratch", required=True)
    ap.add_argument("--sdk", action="append", default=[])
    a = ap.parse_args()
    wt = os.path.abspath(a.scratch)
    os.makedirs(BANK, exist_ok=True)
    dropped_path = os.path.join(BANK, "DROPPED.json")
    dropped = json.load(open(dropped_path)) if os.path.exists(dropped_path) else {}
    controls_path = os.path.join(BANK, "CONTROLS.json")
    controls = json.load(open(controls_path)) if os.path.exists(controls_path) else {}
    for sdk in a.sdk or SDKS:
        spec = SDKS[sdk]
        sdk_dir = f"examples/{sdk}-sdk"
        root = os.path.join(wt, sdk_dir)
        gen = generated_names(root, spec["decl"])
        # Known-good control: every case's corrected line, in one file.
        fixed = [c[1] for c in spec["cases"].values()]
        text, _ = render(sdk, spec, "control", fixed)
        code, err = compile_case(wt, spec["package"], sdk_dir, "cb_control", text)
        open(os.path.join(BANK, f"{sdk}.control.rs"), "w").write(text)
        controls[sdk] = {"compiles": code == 0, "first_error": "\n".join(first_block(err)[:6])}
        print(json.dumps({"sdk": sdk, "control_compiles": code == 0}), flush=True)
        for case, (bad, good, expected, variant) in spec["cases"].items():
            name = f"{sdk}.{case}"
            test_name = f"cb_{case}"
            text, seeded = render(sdk, spec, case, bad)
            user_file = f"{sdk_dir}/tests/{test_name}.rs"
            code, err = compile_case(wt, spec["package"], sdk_dir, test_name, text)
            for ext in (".rs", ".stderr", ".json"):
                if os.path.exists(os.path.join(BANK, name + ext)):
                    os.remove(os.path.join(BANK, name + ext))
            words = set(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", text))
            if code == 0:
                # The seeded mistake compiles: a diagnostics failure (nothing told the caller), kept
                # in the fixed corpus with an empty .stderr so the scorer counts it as failed.
                dropped.pop(name, None)
                meta = {"user_file": user_file, "expected": expected, "compiled": True,
                        "generated_names": [g for g in gen if g not in words],
                        "sdk": sdk, "package": spec["package"], "kind": case, "seeded_line": seeded,
                        "seeded": bad, "corrected": good, "variant": variant}
                open(os.path.join(BANK, name + ".rs"), "w").write(text)
                open(os.path.join(BANK, name + ".stderr"), "w").write("")
                json.dump(meta, open(os.path.join(BANK, name + ".json"), "w"), indent=1, sort_keys=True)
                print(json.dumps({"case": name, "kept": True, "compiled": True}), flush=True)
                continue
            block = first_block(err)
            if not concerns_line(block, user_file, seeded):
                dropped[name] = {"reason": "first error does not concern the seeded line",
                                 "line": bad, "first_error": "\n".join(block[:8])}
                open(os.path.join(BANK, name + ".rs.dropped"), "w").write(text)
                open(os.path.join(BANK, name + ".stderr.dropped"), "w").write(err)
                print(json.dumps({"case": name, "dropped": "other first error"}), flush=True)
                continue
            dropped.pop(name, None)
            meta = {"user_file": user_file, "expected": expected,
                    "generated_names": [g for g in gen if g not in words],
                    "sdk": sdk, "package": spec["package"], "kind": case, "seeded_line": seeded,
                    "seeded": bad, "corrected": good, "variant": variant}
            open(os.path.join(BANK, name + ".rs"), "w").write(text)
            open(os.path.join(BANK, name + ".stderr"), "w").write(err)
            json.dump(meta, open(os.path.join(BANK, name + ".json"), "w"), indent=1, sort_keys=True)
            print(json.dumps({"case": name, "kept": True, "headline": block[0][:120]}), flush=True)
    json.dump(dropped, open(dropped_path, "w"), indent=1, sort_keys=True)
    json.dump(controls, open(controls_path, "w"), indent=1, sort_keys=True)


if __name__ == "__main__":
    main()
