#!/usr/bin/env python3
"""A large synthetic SDK declaration for `validate_header_names()` (H12).

Generates crates/concord/tests/synthetic_sdk.rs. Run from anywhere:

    python3 -I tests-gen/synthetic_sdk.py            # (re)write the Rust file
    python3 -I tests-gen/synthetic_sdk.py --check    # exit 1 if the file is stale

Shape (deterministic): a client with a native credential key and a native `ACCEPT`; SCOPES
scopes, each with a native key of its own and ENDPOINTS endpoints. Endpoint i of a scope does,
by i % 6: nothing; `override` the client's key through an alias constant; `remove` and
reintroduce the scope key; `append` a second vendor value; `remove ACCEPT`; an
`override ... else inherit` of the scope key from an optional value. Every chain is coherent, so
the SDK validates; the test also prepares one endpoint of every kind.
"""

import os
import subprocess
import sys

SCOPES = 40
ENDPOINTS = 12
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "crates", "concord", "tests", "synthetic_sdk.rs")


def endpoint(s, i):
    kind = i % 6
    name = f"e{i}"
    if kind == 0:
        return f'            GET {name}() {{ path "{name}"; }}'
    if kind == 1:
        return f'            GET {name}() {{ path "{name}"; headers {{ override TOKEN_ALIAS = "Bearer s{s}"; }} }}'
    if kind == 2:
        return f'            GET {name}() {{ path "{name}"; headers {{ remove X_SCOPE; X_SCOPE = "again"; }} }}'
    if kind == 3:
        return f'            GET {name}() {{ path "{name}"; headers {{ append X_VENDOR = "{s}.{i}"; }} }}'
    if kind == 4:
        return f'            GET {name}() {{ path "{name}"; headers {{ remove ACCEPT; }} }}'
    return (f'            GET {name}(tenant?: String) {{ path "{name}"; '
            f'headers {{ override X_SCOPE = tenant else inherit; }} }}')


def render():
    lines = [
        "//! Generated by `tests-gen/synthetic_sdk.py`; do not edit. A large synthetic SDK whose",
        "//! header chains all write native `HeaderName` constants: `validate_header_names()` checks",
        f"//! all {SCOPES * ENDPOINTS} endpoints without building anything (H12).",
        "",
        "use concord::reqwest;",
        "use concord::reqwest::header::{ACCEPT, AUTHORIZATION, HeaderName};",
        "",
        "/// The credential header, under another name.",
        "pub const TOKEN_ALIAS: HeaderName = AUTHORIZATION;",
        "/// A per-scope header.",
        'pub const X_SCOPE: HeaderName = HeaderName::from_static("x-scope");',
        "/// A vendor header.",
        'pub const X_VENDOR: HeaderName = HeaderName::from_static("x-vendor");',
        "",
        "concord::api! {",
        "    /// The synthetic SDK.",
        "    pub client Synthetic(#[sensitive] header(AUTHORIZATION) token: String) {",
        '        base "https://synthetic.invalid/v1";',
        '        headers { ACCEPT = "application/json"; X_VENDOR = "sdk"; }',
    ]
    for s in range(SCOPES):
        lines.append(f'        scope s{s} {{')
        lines.append(f'            path "s{s}";')
        lines.append(f'            headers {{ X_SCOPE = "s{s}"; }}')
        for i in range(ENDPOINTS):
            lines.append(endpoint(s, i))
        lines.append("        }")
    lines += [
        "    }",
        "}",
        "",
        "#[test]",
        "fn the_synthetic_sdk_validates_without_building_anything() {",
        "    Synthetic::validate_header_names().unwrap();",
        "}",
        "",
        "#[test]",
        "fn every_kind_of_endpoint_prepares() {",
        '    let api = Synthetic::new(reqwest::Client::new(), SyntheticConfig { token: "t".into() });',
        f"    let s = api.s{SCOPES - 1}();",
        "    for result in [",
    ]
    for i in range(6):
        lines.append(f"        s.e{i}().prepare().map(drop),")
    lines += [
        "    ] {",
        "        result.unwrap();",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def formatted(text):
    """The text as `cargo fmt` leaves it (the repository's rustfmt.toml applies)."""
    return subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout", "--config-path", ROOT],
        input=text, capture_output=True, text=True, check=True, cwd=ROOT).stdout


def main():
    text = formatted(render())
    if sys.argv[1:] == ["--check"]:
        with open(OUT, encoding="utf-8") as f:
            return 0 if f.read() == text else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
