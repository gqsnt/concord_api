const ARCHIVE_SIZE: usize = 40_000;
const SIGNATURE: &str = "sig=SYNTHETIC_SIGNATURE_xyz789";

/// The deterministic archive bytes (seed 41): position-dependent, so reordering or loss shows.
fn archive() -> Vec<u8> {
    (0..ARCHIVE_SIZE)
        .map(|i| ((i * 131 + 41) % 256) as u8)
        .collect()
}

/// What the download host does.
#[derive(Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
enum Delivery {
    Archive = 0,
    FailMidBody = 1,
    Slow = 2,
    SignatureExpired = 3,
}

#[derive(Default)]
struct Switches {
    expired_metadata: AtomicBool,
    download_gone: AtomicBool,
    delivery: AtomicU8,
}

fn repo_id(path: &str) -> Option<(&'static str, String)> {
    for (name, id) in [("hello-world", "101"), ("second-repo", "202")] {
        for prefix in [
            format!("/repos/octo-org/{name}"),
            format!("/repositories/{id}"),
        ] {
            if let Some(rest) = path.strip_prefix(&prefix) {
                return Some((id_static(id), rest.to_owned()));
            }
        }
    }
    None
}

fn id_static(id: &str) -> &'static str {
    if id == "101" { "101" } else { "202" }
}

fn api(switches: Arc<Switches>, download_port: u16) -> impl Fn(&Recorded) -> Reply + Send + Sync {
    move |r: &Recorded| {
        let o = origin(r);
        let Some((id, rest)) = repo_id(r.path()) else {
            return gh_error(404, r#"{"message":"Not Found","status":"404"}"#);
        };
        let q = r.query().unwrap_or("");
        match (rest.as_str(), q) {
            ("/actions/runs", "branch=main&event=push&per_page=2") => {
                gh_json(fixture!("runs-a-1.json"), 1).header(
                    "link",
                    format!("<{o}/repositories/{id}/actions/runs?branch=main&event=push&per_page=2&page=2>; rel=\"next\""),
                )
            }
            ("/actions/runs", "branch=main&event=push&per_page=2&page=2") => {
                gh_json(fixture!("runs-a-2.json"), 2)
            }
            ("/actions/runs/9003", "") => gh_json(fixture!("run-a-9003.json"), 3),
            ("/actions/runs/9003/jobs", "") => gh_json(fixture!("jobs-a-9003-1.json"), 4)
                .header(
                    "link",
                    format!("<{o}/repositories/{id}/actions/runs/9003/jobs?page=2>; rel=\"next\""),
                ),
            ("/actions/runs/9003/jobs", "page=2") => gh_json(fixture!("jobs-a-9003-2.json"), 5),
            ("/actions/runs/9003/artifacts", "name=coverage-report") => {
                if switches.expired_metadata.load(Ordering::SeqCst) {
                    gh_json(fixture!("artifacts-a-9003-expired.json"), 6)
                } else {
                    gh_json(fixture!("artifacts-a-9003.json"), 6)
                }
            }
            ("/actions/runs/9003/artifacts", _) => {
                gh_json(r#"{"total_count":0,"artifacts":[]}"#, 6)
            }
            ("/actions/artifacts/5001", "") => gh_json(fixture!("artifact-a-5001.json"), 7),
            ("/actions/artifacts/5002", "") => gh_json(fixture!("artifact-a-5002.json"), 7),
            ("/actions/artifacts/5001/zip", "") => {
                if switches.download_gone.load(Ordering::SeqCst) {
                    return gh_error(410, fixture!("error-410.json"));
                }
                Reply::new(302)
                    .header(
                        "location",
                        format!("http://{DOWNLOAD_HOST}:{download_port}/blobs/{id}/5001.zip?{SIGNATURE}"),
                    )
                    .header("x-github-request-id", "REQ:0302")
                    .header("x-ratelimit-remaining", "4990")
            }
            _ => gh_error(404, r#"{"message":"Not Found","status":"404"}"#),
        }
    }
}

fn download(switches: Arc<Switches>) -> impl Fn(&Recorded) -> Reply + Send + Sync {
    move |_: &Recorded| match switches.delivery.load(Ordering::SeqCst) {
        0 => {
            let chunks = archive()
                .chunks(6_000)
                .map(|c| (Duration::ZERO, Bytes::copy_from_slice(c)))
                .collect();
            Reply::new(200)
                .header("content-type", "application/zip")
                .with_body(Body::Chunks(chunks))
        }
        1 => {
            let bytes = archive();
            Reply::new(200)
                .header("content-type", "application/zip")
                .with_body(Body::FailAfter(vec![
                    Bytes::copy_from_slice(&bytes[..10_000]),
                    Bytes::copy_from_slice(&bytes[10_000..15_000]),
                ]))
        }
        2 => Reply::new(200).with_body(Body::Generate(
            // 64 MiB on demand, one 16 KiB chunk per millisecond: never materialized.
            generated_records(4096, 16 * 1024, |i| vec![(i % 251) as u8; 16 * 1024]),
            Some(Duration::from_millis(1)),
        )),
        _ => Reply::text(
            403,
            "application/xml",
            "<Error><Code>AuthenticationFailed</Code></Error>",
        ),
    }
}

struct Fixture {
    api: TestServer,
    download: TestServer,
    switches: Arc<Switches>,
}

impl Fixture {
    async fn start() -> Self {
        let switches = Arc::new(Switches::default());
        let download = TestServer::start(download(switches.clone())).await;
        let api = TestServer::start(api(switches.clone(), download.addr().port())).await;
        Self {
            api,
            download,
            switches,
        }
    }

    fn repo(&self, name: &str, token: &str) -> concord_example_github_sdk::RepoContext {
        github(self.api.addr(), Some(self.download.addr()), token)
            .repo(RepoRef::new("octo-org", name))
    }

    fn deliver(&self, delivery: Delivery) {
        self.switches
            .delivery
            .store(delivery as u8, Ordering::SeqCst);
    }

    async fn shutdown(self) {
        assert_eq!(self.api.shutdown().await.open_after, 0);
        assert_eq!(self.download.shutdown().await.open_after, 0);
    }
}

fn input(artifact: &str) -> RetrievalInput {
    let pages = NonZeroUsize::new(5).unwrap();
    RetrievalInput {
        runs: RunFilter {
            branch: Some("main".into()),
            event: Some("push".into()),
            per_page: Some(PerPage::new(2).unwrap()),
            ..RunFilter::default()
        },
        select: RunSelector {
            conclusion: Some(Conclusion::Success),
        },
        artifact_name: artifact.to_owned(),
        budget: RetrievalBudget {
            run_pages: pages,
            job_pages: pages,
            artifact_pages: pages,
        },
        limits: DownloadLimits { max_bytes: 1 << 20 },
    }
}

fn scratch(name: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR"))
        .join("gh_b")
        .join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir.join("coverage-report.zip")
}

/// The full retrieval: a run selected on the second runs page (absent `last`), its jobs over two
/// pages, the artifact found by name in its envelope, `302` to the download host, the archive
/// streamed into a file and committed. The download host never sees the token or GitHub's
/// headers.
#[tokio::test]
async fn retrieves_into_a_file_without_forwarding_the_token() {
    let fx = Fixture::start().await;
    fx.deliver(Delivery::Archive);
    let repo = fx.repo("hello-world", TOKEN_A);
    let path = scratch("retrieved");
    let mut sink = FileSink::new(&path, 1 << 20);

    let retrieval = retrieve_artifact(&repo, &input("coverage-report"), &mut sink).await;
    let RetrievalOutcome::Retrieved(report) = &retrieval.outcome else {
        panic!("{:?}", retrieval.outcome)
    };
    assert_eq!(report.run.id, RunId(9003));
    assert_eq!(report.run.runs_scanned, 3);
    assert_eq!(
        report.jobs.jobs.iter().map(|j| j.id).collect::<Vec<_>>(),
        [JobId(7001), JobId(7002)]
    );
    assert!(report.jobs.complete);
    assert_eq!(report.jobs.total_count, Some(2));
    assert_eq!(report.artifact.id, ArtifactId(5001));
    assert_eq!(report.receipt.bytes, ARCHIVE_SIZE as u64);
    assert!(report.receipt.chunks >= 2);
    assert!(report.receipt.size_matches);
    assert_eq!(report.receipt.host, DOWNLOAD_HOST);
    assert_eq!(
        report.receipt.redirect_request_id.as_deref(),
        Some("REQ:0302")
    );
    assert_eq!(std::fs::read(&path).unwrap(), archive());
    assert!(!sink.partial_path().exists());

    let api_wire = fx.api.requests();
    let targets: Vec<&str> = api_wire.iter().map(|r| r.target.as_str()).collect();
    assert_eq!(
        targets,
        [
            "/repos/octo-org/hello-world/actions/runs?branch=main&event=push&per_page=2",
            "/repositories/101/actions/runs?branch=main&event=push&per_page=2&page=2",
            "/repos/octo-org/hello-world/actions/runs/9003",
            "/repos/octo-org/hello-world/actions/runs/9003/jobs",
            "/repositories/101/actions/runs/9003/jobs?page=2",
            "/repos/octo-org/hello-world/actions/runs/9003/artifacts?name=coverage-report",
            "/repos/octo-org/hello-world/actions/artifacts/5001",
            "/repos/octo-org/hello-world/actions/artifacts/5001/zip",
        ]
    );
    for request in &api_wire {
        assert_api_request(request, TOKEN_A);
    }
    let fetched = fx.download.single();
    assert_eq!(fetched.target, format!("/blobs/101/5001.zip?{SIGNATURE}"));
    for header in ["authorization", "x-github-api-version", "user-agent"] {
        assert!(
            fetched.header(header).is_none(),
            "{header} reached the download host"
        );
    }
    assert_eq!(retrieval.requests.len(), 8);
    assert_eq!(retrieval.requests[7].status, Some(302));
    let shown = format!("{retrieval:?}");
    assert!(!shown.contains("SYNTHETIC_SIGNATURE") && !shown.contains(TOKEN_A));
    fx.shutdown().await;
}

