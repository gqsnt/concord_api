//! GH-B end to end against two loopback servers: the GitHub API stand-in (synthetic fixtures of
//! `tests/fixtures/MANIFEST.json`) and a separate download host reached through
//! `reqwest::ClientBuilder::resolve`, as GitHub's signed artifact URLs are.
//!
//! Runs for `branch=main&event=push&per_page=2`: page 1 = run 9001 (in progress) and 9002
//! (failure) with `Link: next` and no `last`; page 2 = run 9003 (success), no `Link`. Run 9003 has
//! jobs on two pages and the artifact `coverage-report` (5001, 40,000 bytes). The download endpoint
//! answers `302` to the download host (or `410`); the download host streams generated bytes or a
//! scripted failure.
//!
//! Run: `cargo test -p concord-example-github-app --test gh_b_artifact_retrieval`.

