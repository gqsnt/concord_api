use super::*;

/// Money in the smallest denomination of the indicated currency; never a float.
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
pub struct Money {
    /// Integer minor units (for example USD cents).
    pub amount: i64,
    /// ISO 4217 currency spelling, such as `USD`.
    pub currency: String,
}

/// Minimal token-based, immediate-capture create body. Fields are immutable after validation.
///
/// Clone this body or the generated operation for an exact replay. This slice does
/// not accept cash/external payments or card-on-file inputs requiring other fields.
#[derive(Clone, Serialize)]
pub struct CreatePayment {
    source_id: String,
    idempotency_key: String,
    amount_money: Money,
    autocomplete: bool,
}

impl CreatePayment {
    /// Constructs a payment using a previously collected payment token.
    ///
    /// Requires a 1–45 byte key, nonempty source, positive amount and three
    /// uppercase ASCII currency letters. Currency/account compatibility and
    /// source validity remain Square's checks. No key is generated by this SDK.
    pub fn new(
        idempotency_key: impl Into<String>,
        source_id: impl Into<String>,
        amount_money: Money,
    ) -> Result<Self, InputError> {
        let idempotency_key = idempotency_key.into();
        let source_id = source_id.into();
        if idempotency_key.is_empty() || idempotency_key.len() > 45 {
            return Err(InputError::IdempotencyKey);
        }
        if source_id.is_empty()
            || source_id == "CASH"
            || source_id == "EXTERNAL"
            || source_id.starts_with("ccof:")
        {
            return Err(InputError::Source);
        }
        if amount_money.amount <= 0 {
            return Err(InputError::Amount);
        }
        if amount_money.currency.len() != 3
            || !amount_money
                .currency
                .bytes()
                .all(|b| b.is_ascii_uppercase())
        {
            return Err(InputError::Currency);
        }
        Ok(Self {
            source_id,
            idempotency_key,
            amount_money,
            autocomplete: true,
        })
    }
}

impl fmt::Debug for CreatePayment {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("CreatePayment(<redacted>)")
    }
}

/// An input was refused before building an HTTP request. No input is retained.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InputError {
    /// The key is empty or exceeds this slice's conservative 45-byte limit.
    IdempotencyKey,
    /// A token source is required; cash and external details are excluded.
    Source,
    /// This slice requires a positive amount.
    Amount,
    /// Currency must be three uppercase ASCII letters.
    Currency,
}

impl fmt::Display for InputError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::IdempotencyKey => "idempotency key must contain 1 to 45 bytes",
            Self::Source => "a nonempty payment token source is required",
            Self::Amount => "payment amount must be positive",
            Self::Currency => "currency must be three uppercase ASCII letters",
        })
    }
}

impl std::error::Error for InputError {}

/// The retained accounting/inspection fields of a Square payment.
/// Additional provider fields are ignored, including card details and receipt URLs.
#[derive(Clone, Debug, Deserialize, PartialEq, Eq)]
pub struct Payment {
    /// Provider payment identity, used with `payments().get(id)`.
    pub id: String,
    /// Amount in minor units with currency.
    pub amount_money: Money,
    /// Provider status, preserved verbatim for forward compatibility.
    pub status: String,
}

/// Successful CreatePayment or GetPayment envelope.
#[derive(Debug, Deserialize)]
pub struct PaymentResponse {
    /// Created or retrieved payment.
    pub payment: Payment,
}

/// One ListPayments response. Omitted payments mean an empty page.
#[derive(Deserialize)]
pub struct PaymentsPage {
    /// Payments in the order returned by Square.
    #[serde(default)]
    pub payments: Vec<Payment>,
    /// Opaque continuation; absent/empty means the last page.
    pub cursor: Option<String>,
}

impl fmt::Debug for PaymentsPage {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("PaymentsPage")
            .field("payments", &self.payments.len())
            .field("cursor_present", &self.cursor.is_some())
            .finish()
    }
}
